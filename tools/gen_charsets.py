#!/usr/bin/env python3
"""Generate exact per-glyph Rust charset maps from CPython's strict codecs.

Adapted in concept and registry semantics from bdfparser/encoding.py and
bdfparser-js/tools/gen_charsets.py (MIT, Tom Chen). See THIRD_PARTY_NOTICES.md.
No third-party Python packages or reference checkout are needed. Run with
Python >= 3.12. --check validates checked-in output without modifying it.
This is NOT an ISO-2022 stream converter: iso2022cn is SPEC's GB2312 GL alias.
"""
from __future__ import annotations

import argparse
import bisect
import hashlib
import json
import sys
from pathlib import Path

sys.dont_write_bytecode = True
ROOT = Path(__file__).resolve().parents[1]
REGISTRY_PATH = ROOT / 'tools/charsets/registry.json'
HEADER = '// @generated by tools/gen_charsets.py; do not edit.\n// Exact CPython codec data; see THIRD_PARTY_NOTICES.md and docs/charsets.md.\n'
MASK = 0xFFFFFFFFFFFFFFFF
INDEX_FLAG = 0x80000000


def load_registry():
    return json.loads(REGISTRY_PATH.read_text())


def decode(code: int, info: dict, gl: bool = False) -> int | None:
    """SPEC per-glyph semantics, not general byte-stream decoding."""
    if info['kind'] == 'unicode':
        return code if 0 <= code <= 0x10FFFF else None
    if code < 0 or code > 0xFFFFFFFF:
        return None
    if info['kind'] == 'sbcs' and code >= 0x100:
        return None
    if code < 0x100:
        data = bytes([code])
    elif code < 0x10000:
        if gl:
            if not (0x21 <= code >> 8 <= 0x7E and 0x21 <= code & 255 <= 0x7E):
                return None
            code += 0x8080
        data = code.to_bytes(2, 'big')
    elif info['kind'] == 'gb18030':
        data = code.to_bytes(4, 'big')
    else:
        return None
    try:
        value = data.decode(info['codec'], 'strict')
    except UnicodeDecodeError:
        return None
    return ord(value) if len(value) == 1 else None


def encode(value: int, info: dict, gl: bool = False) -> int | None:
    if info['kind'] == 'unicode':
        return value if 0 <= value <= 0x10FFFF else None
    try:
        data = chr(value).encode(info['codec'], 'strict')
    except (UnicodeEncodeError, ValueError):
        return None
    allowed = {'sbcs': (1,), 'dbcs': (1, 2), 'gb18030': (1, 2, 4)}[info['kind']]
    if len(data) not in allowed:
        return None
    code = int.from_bytes(data, 'big')
    if gl and len(data) == 2:
        code -= 0x8080
    return code if decode(code, info, gl) == value else None


def gb_code(index: int) -> int:
    fourth = index % 10 + 0x30
    index //= 10
    third = index % 126 + 0x81
    index //= 126
    second = index % 10 + 0x30
    first = index // 10 + 0x81
    return (first << 24) | (second << 16) | (third << 8) | fourth


def gb_ranges():
    """Enumerate ALL 126*10*126*10 sequences; never assume supplementary runs."""
    runs = []
    for index in range(126 * 10 * 126 * 10):
        code = gb_code(index)
        try:
            value = code.to_bytes(4, 'big').decode('gb18030', 'strict')
        except UnicodeDecodeError:
            continue
        assert len(value) == 1
        value = ord(value)
        if runs and runs[-1][0] + runs[-1][2] == index and runs[-1][1] + runs[-1][2] == value:
            runs[-1][2] += 1
        else:
            runs.append([index, value, 1])
    # Each reverse range must also be ordered and disjoint.
    assert all(a[1] + a[2] <= b[1] for a, b in zip(runs, runs[1:]))
    return runs


def packed(mapping):
    """Binary-searchable sparse segments + dense u32 arrays + linear runs."""
    pairs = sorted(mapping.items())
    segments, data = [], []
    i = 0
    while i < len(pairs):
        j = i + 1
        while j < len(pairs) and pairs[j][0] == pairs[j - 1][0] + 1:
            j += 1
        # One contiguous key range: extract ascending runs of >= 4 values.
        p = i
        while p < j:
            q = p + 1
            while q < j and pairs[q][1] == pairs[q - 1][1] + 1:
                q += 1
            if q - p >= 4:
                segments.append((pairs[p][0], pairs[q - 1][0], pairs[p][1]))
                p = q
            else:
                end = q
                while end < j:
                    r = end + 1
                    while r < j and pairs[r][1] == pairs[r - 1][1] + 1:
                        r += 1
                    if r - end >= 4:
                        break
                    end = r
                segments.append((pairs[p][0], pairs[end - 1][0], INDEX_FLAG | len(data)))
                data.extend(value for _, value in pairs[p:end])
                p = end
        i = j
    # Validate compression independently of the Rust implementation.
    expanded = {}
    for start, end, value in segments:
        for offset, key in enumerate(range(start, end + 1)):
            expanded[key] = data[(value & ~INDEX_FLAG) + offset] if value & INDEX_FLAG else value + offset
    assert expanded == mapping
    return segments, data


def rust_map(mapping):
    segments, data = packed(mapping)
    lines = ['Map {', '    segments: &[']
    for start, end, value in segments:
        lines.append(f'        Segment {{ start: 0x{start:X}, end: 0x{end:X}, value: 0x{value:X} }},')
    lines += ['    ],', '    data: &[']
    for i in range(0, len(data), 10):
        lines.append('        ' + ', '.join(f'0x{v:X}' for v in data[i:i + 10]) + ',')
    lines += ['    ],', '}']
    return '\n'.join(lines), len(segments) * 12 + len(data) * 4, len(segments), len(data)


def hash_pairs(pairs):
    value = 0xCBF29CE484222325
    count = 0
    for key, mapped in pairs:
        for byte in key.to_bytes(4, 'little') + mapped.to_bytes(4, 'little'):
            value = ((value ^ byte) * 0x100000001B3) & MASK
        count += 1
    return {'count': count, 'fnv1a64': f'{value:016x}'}


def transformed(mapping, reverse, gl):
    if not gl:
        return mapping, reverse
    forward = {code if code < 256 else code - 0x8080: value for code, value in mapping.items()
               if code < 256 or (0xA1 <= code >> 8 <= 0xFE and 0xA1 <= code & 255 <= 0xFE)}
    rev = {}
    for value, code in reverse.items():
        code = code if code < 256 else code - 0x8080
        if forward.get(code) == value:
            rev[value] = code
    return forward, rev


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    if sys.version_info < (3, 12):
        parser.error('Python 3.12 or later is required')
    reg = load_registry()
    tables, ids, dedup = {'core': [], 'cjk': []}, {}, {}
    stats = {}
    for key, info in reg['charsets'].items():
        if info['kind'] == 'unicode':
            continue
        cachekey = (info['codec'], info['kind'])
        if cachekey in dedup:
            ids[key] = dedup[cachekey]
            continue
        top = 256 if info['kind'] == 'sbcs' else 65536
        mapping = {}
        for code in range(top):
            value = decode(code, info)
            if value is not None:
                mapping[code] = value
        reverse = {}
        for value in sorted(set(mapping.values())):
            code = encode(value, info)
            if code is not None:
                reverse[value] = code
        group = 'core' if info['kind'] == 'sbcs' else 'cjk'
        # Identical aliases, including Python's cp936/gbk, share physical tables.
        ident = next((i for i, (_, m, r) in enumerate(tables[group]) if m == mapping and r == reverse), None)
        if ident is None:
            ident = len(tables[group])
            tables[group].append((key, mapping, reverse))
        ids[key] = dedup[cachekey] = (group, ident)
    runs = gb_ranges()
    ginfo = reg['charsets']['gb18030']
    _, gm, gr = tables['cjk'][ids['gb18030'][1]]
    starts = [r[1] for r in runs]
    # Verify the 4-byte reverse algorithm for EVERY scalar, including the
    # encoder's preference for 1/2-byte codes and any non-roundtripping aliases.
    for value in range(0x110000):
        code = gr.get(value)
        if code is None:
            i = bisect.bisect_right(starts, value) - 1
            if i >= 0 and value < runs[i][1] + runs[i][2]:
                code = gb_code(runs[i][0] + value - runs[i][1])
        assert code == encode(value, ginfo), (hex(value), code)
    outputs = {}
    for group, entries in tables.items():
        lines = [HEADER, 'use super::{Map, Segment, Table};', '', '#[rustfmt::skip]', 'pub(super) static TABLES: &[Table] = &[']
        for key, forward, reverse in entries:
            d, dsize, dseg, ddata = rust_map(forward)
            e, esize, eseg, edata = rust_map(reverse)
            lines += [f'    // {key}', '    Table {', '        decode: ' + d + ',', '        encode: ' + e + ',', '    },']
            stats[key] = {'group': group, 'decode_count': len(forward), 'encode_count': len(reverse),
                          'segments': dseg + eseg, 'dense_values': ddata + edata, 'data_bytes': dsize + esize}
        lines += ['];', '']
        if group == 'cjk':
            lines += ['#[rustfmt::skip]', 'pub(super) static GB18030: &[(u32, u32, u32)] = &[']
            lines += [f'    (0x{index:X}, 0x{value:X}, {length}),' for index, value, length in runs]
            lines += ['];', '']
        outputs[ROOT / f'crates/fontpixel/src/charset/{group}.rs'] = '\n'.join(lines)
    lines = [HEADER, 'use super::{CharsetInfo, Kind, TableId};', '', '#[rustfmt::skip]', 'pub(super) static CHARSETS: &[CharsetInfo] = &[']
    kinds = {'unicode': 'Unicode', 'sbcs': 'SingleByte', 'dbcs': 'DoubleByte', 'gb18030': 'Gb18030'}
    for key, info in reg['charsets'].items():
        table = 'None' if key not in ids else f'Some(TableId::{ids[key][0].title()}({ids[key][1]}))'
        codec = 'None' if info['codec'] is None else f'Some({json.dumps(info["codec"])})'
        aliases = ', '.join(json.dumps(a) for a in info['aliases'])
        lines += [f'    CharsetInfo {{ key: "{key}", python_codec: {codec}, kind: Kind::{kinds[info["kind"]]}, gl_capable: {str(info["gl"]).lower()}, force_gl: {str(info["forcegl"]).lower()}, properties: ("{info["props"][0]}", "{info["props"][1]}"), aliases: &[{aliases}], table: {table} }},']
    lines += ['];', '', 'pub(super) static UNICODE_PREFIXES: &[&str] = &[' + ', '.join(json.dumps(s) for s in reg['unicode_prefixes']) + '];', '']
    outputs[ROOT / 'crates/fontpixel/src/charset/registry.rs'] = '\n'.join(lines)
    golden = {}
    for key, info in reg['charsets'].items():
        if info['kind'] == 'unicode':
            continue
        group, ident = ids[key]
        _, forward, reverse = tables[group][ident]
        modes = [info['forcegl']]
        if info['gl'] or info['forcegl']:
            modes = [False, True]
        for gl in modes:
            fwd, rev = transformed(forward, reverse, gl)
            golden[key + ('/gl' if gl else '')] = {'decode': hash_pairs(sorted(fwd.items())), 'encode': hash_pairs(sorted(rev.items()))}
    golden['gb18030/4'] = {'decode': hash_pairs((gb_code(i + o), c + o) for i, c, n in runs for o in range(n)),
                           'encode': hash_pairs((c + o, gb_code(i + o)) for i, c, n in runs for o in range(n))}
    outputs[ROOT / 'crates/fontpixel/tests/data/charset_maps.json'] = json.dumps(golden, indent=2, sort_keys=True) + '\n'
    manifest = {'registry_sha256': hashlib.sha256(REGISTRY_PATH.read_bytes()).hexdigest(),
                'unique_core_tables': len(tables['core']), 'unique_cjk_tables': len(tables['cjk']),
                'gb18030_four_byte_ranges': len(runs), 'gb18030_four_byte_count': sum(n for _, _, n in runs),
                'tables': stats}
    outputs[ROOT / 'tools/charsets/manifest.json'] = json.dumps(manifest, indent=2, sort_keys=True) + '\n'
    mismatches = []
    for path, output in outputs.items():
        if args.check:
            if not path.exists() or path.read_text() != output:
                mismatches.append(str(path.relative_to(ROOT)))
        else:
            path.write_text(output)
    if mismatches:
        print('Generated data differs: ' + ', '.join(mismatches), file=sys.stderr)
        return 1
    print(f'{"Verified" if args.check else "Generated"} {len(ids)} non-Unicode keys; '
          f'{len(tables["core"])} core + {len(tables["cjk"])} CJK unique tables; '
          f'{len(runs)} GB18030 ranges ({sum(n for _, _, n in runs):,} four-byte mappings); '
          f'CPython {sys.version.split()[0]}')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
