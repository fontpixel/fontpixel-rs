#!/usr/bin/env python3
"""CPython Unicode printability for exact repr() in SPEC diagnostic messages."""
import argparse
from pathlib import Path
import sys, unicodedata
ROOT=Path(__file__).resolve().parents[1]
def main():
    parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
    ranges=[];start=None
    for n in range(0x110001):
        bad=n<0x110000 and not chr(n).isprintable()
        if bad and start is None:start=n
        if not bad and start is not None:ranges.append((start,n-1));start=None
    lines=[f'// Generated by tools/gen_bdf_printable.py; CPython {sys.version_info.major}.{sys.version_info.minor}, Unicode {unicodedata.unidata_version}.',
           '// Unicode printability facts only; see THIRD_PARTY_NOTICES.md.',
           'pub(super) const NONPRINTABLE: &[(u32, u32)] = &[']
    lines.extend(f'    (0x{a:x}, 0x{b:x}),' for a,b in ranges)
    lines += ['];','']
    payload='\n'.join(lines);target=ROOT/'crates/fontpixel/src/formats/bdf/nonprintable.rs'
    if args.check:
        if target.read_text()!=payload:raise SystemExit('BDF diagnostic printability table drift')
    else:target.write_text(payload)
    print(f'BDF printability: {len(ranges)} ranges')
if __name__=='__main__':main()
