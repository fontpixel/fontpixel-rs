#!/usr/bin/env python3
"""Generate the JS reference from built declarations and coverage rules.

Run after scripts/build_wasm.sh full. --check verifies the committed reference.
The wasm-bindgen declarations include Rust doc comments and serde types.
"""
import argparse
import os
import re
from pathlib import Path
import tomllib

ROOT = Path(__file__).resolve().parents[2]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--pkg", type=Path, default=Path(os.environ.get("CARGO_TARGET_DIR", ROOT / "target")) / "wasm-pkg/full")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    files = ["index.d.ts", "fontpixel_wasm.d.ts", "model.d.ts", "errors.d.ts", "resources.d.ts", "ops-client.d.ts", "ops-node-files.d.ts", "compat_bdfparser.d.ts", "compat_bdfparser_cjk.d.ts", "compat_bdfparser_cli.d.ts"]
    sections = ["# JavaScript / TypeScript API reference\n\nGenerated by `tools/bindings/gen_jsref.py` from a **full** package. Read [the JS guide](js-api.md) for ownership, profiles and examples. Declarations list the complete API; availability still depends on the selected build's `capabilities()` and `formats.catalogue()`. Compiler-generated `wasm_bindgen_*` closure exports in the raw `InitOutput` are omitted because their mangled names depend on code generation; the packaged `.d.ts` retains them.\n"]
    for name in files:
        declaration = (args.pkg / name).read_text().rstrip()
        declaration = re.sub(r"^    readonly wasm_bindgen_[^\n]+\n", "", declaration, flags=re.MULTILINE)
        sections.append(f"## {name}\n\n```typescript\n{declaration}\n```\n")
    sections.append("## Native mapping and explicit exceptions\n\nEach rule below is checked against the Rust public inventory by `tools/bindings/gate.sh python,js`. A mapping does not imply that a disabled feature works in every profile.\n")
    for file in sorted((ROOT / "bindings/coverage").glob("*.toml")):
        sections.append(f"### {file.stem}\n\n| Rust pattern | Status | JS entry / reason |\n| --- | --- | --- |")
        for rule in tomllib.loads(file.read_text())["rule"]:
            def cell(value):
                return str(value).replace("|", "\\|").replace("\n", " ")
            detail = rule.get("js", "")
            if rule.get("reason"):
                detail += "; " + rule["reason"]
            sections.append(f"| `{cell(rule['pattern'])}` | {cell(rule['status'])} | {cell(detail)} |")
        sections.append("")
    result = "\n".join(sections)
    out = ROOT / "docs/js-api-reference.md"
    if args.check:
        if not out.exists() or out.read_text() != result:
            raise SystemExit("JS reference stale: run tools/bindings/gen_jsref.py after building full")
        print("JS reference up to date")
    else:
        out.write_text(result)
        print(f"wrote {out.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
