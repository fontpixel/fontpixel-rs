#!/usr/bin/env python3
"""Generate bindings/coverage/formats.toml from the rustdoc inventory.

One rule per public item of `fontpixel::formats` (plus the crate-root
`read`/`write`/`registry`/`FontRegistry`), and per format module a `::**`
catch-all for its serde option/codec types and enums. The generator refuses to
run (exit 2) when the inventory has an item it cannot classify: a function,
method or constant without a binding entry below, or a struct/enum that would
fall to a module catch-all but does not derive Deserialize (and so is not in
the `normalize` table generated by tools/bindings/gen_formats_types.py).

Usage:
    tools/bindings/gen_formats_coverage.py [INVENTORY.json] [--check]

INVENTORY defaults to `$FONTPIXEL_RUSTDOC_TARGET/inventory.json` (else
`target/rustdoc-json/inventory.json`), as written by tools/bindings/gate.sh.
`--check` writes nothing and exits 1 when the committed formats.toml differs
from what the inventory produces.
"""
import argparse
import json
import os
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "bindings/coverage/formats.toml"
TYPES = ROOT / "crates/fontpixel-py/src/formats_types.rs"


def default_inventory():
    target = os.environ.get("FONTPIXEL_RUSTDOC_TARGET") or os.path.join(
        os.environ.get("CARGO_TARGET_DIR", "target"), "rustdoc-json")
    return os.path.join(target, "inventory.json")


_ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
_ap.add_argument("inventory", nargs="?", default=default_inventory())
_ap.add_argument("--check", action="store_true")
ARGS = _ap.parse_args()
INV = ARGS.inventory


def unclassified(path, why):
    print(f"unclassified {path}: {why}; add a binding and a rule to "
          "tools/bindings/gen_formats_coverage.py", file=sys.stderr)
    sys.exit(2)

T = "crates/fontpixel-py/tests/"
RT = T + "test_formats_roundtrip.py::"
RG = T + "test_formats_registry.py::"
OP = T + "test_formats_options.py::"
EX = T + "test_formats_extra.py::"

items = json.load(open(INV))["items"]
mine = [i for i in items if i["kind"] not in ("field", "variant") and (
    i["path"].startswith("fontpixel::formats") or i["path"] in (
        "fontpixel::read", "fontpixel::write", "fontpixel::registry", "fontpixel::FontRegistry"))]

normalize_rows = TYPES.read_text()
rules = []
PATHS = {i["path"] for i in mine}


def has(pattern):
    rx = re.compile("^" + re.escape(pattern).replace(r"\*\*", ".+").replace(r"\*", "[^:]*") + "$")
    return any(rx.match(p) for p in PATHS)


def rule(pattern, status, python, test, reason=None, evidence=None):
    if not has(pattern):
        return
    r = {"pattern": pattern, "status": status, "python": python, "python_test": test}
    if reason:
        r["reason"] = reason
    if evidence:
        r["evidence"] = evidence
    rules.append(r)


# --- crate root -----------------------------------------------------------
rule("fontpixel::read", "bound", "fontpixel.read", RG + "test_read_matches_cli_and_reports")
rule("fontpixel::write", "bound", "fontpixel.write", RG + "test_write_strict_mode_and_reports")
rule("fontpixel::registry", "bound", "fontpixel.registry", RG + "test_planned_registry_has_no_codecs")
rule("fontpixel::FontRegistry", "adapted", "fontpixel.Registry", RG + "test_registry_formats_status_and_names",
     "type alias of Registry<FontSet>; the Python Registry class is that specialization")

# --- formats module top level --------------------------------------------
rule("fontpixel::formats", "bound", "fontpixel.formats", EX + "test_namespaces_are_importable_modules")
rule("fontpixel::formats::Confidence", "adapted", "detection result strings ('no_match', 'extension', 'possible', 'certain')",
     RG + "test_detect_content_then_name_hint", "plain data through serde (snake_case strings)")
rule("fontpixel::formats::Detected", "adapted", "dict {'format', 'confidence'} returned by fontpixel.detect / Registry.detect",
     RG + "test_detect_content_then_name_hint", "Serialize-only result returned as a dict")
rule("fontpixel::formats::FormatInfo", "adapted", "dict {'id', 'name', 'extensions', 'feature_enabled'}",
     RG + "test_registry_formats_status_and_names", "Serialize-only catalogue record returned as a dict; input is the id string or a dict for Registry.register")
rule("fontpixel::formats::FormatStatus", "adapted", "dict returned by Registry.formats/status, fontpixel.list_formats",
     RG + "test_registry_formats_status_and_names", "Serialize-only status returned as a dict")
rule("fontpixel::formats::FormatDetector", "adapted", "Registry.register(detector=callable)",
     RG + "test_python_codec_registration", "trait implemented by Python hooks registered on a Registry")
rule("fontpixel::formats::FormatDetector::detect", "adapted", "detector(ctx) -> confidence",
     RG + "test_python_codec_registration", "Python hook called with a ReadContext")
rule("fontpixel::formats::FormatReader", "adapted", "Registry.register(reader=callable)",
     RG + "test_python_codec_registration", "trait implemented by Python hooks registered on a Registry")
rule("fontpixel::formats::FormatReader::read", "adapted", "reader(ctx, options) -> (FontSet, report)",
     RG + "test_python_codec_registration", "Python hook called with a ReadContext and the ReadOptions dict")
rule("fontpixel::formats::FormatWriter", "adapted", "Registry.register(writer=callable or object)",
     RG + "test_python_codec_registration", "trait implemented by Python hooks registered on a Registry")
rule("fontpixel::formats::FormatWriter::write", "adapted", "writer(font_set, options) / writer.write(...)",
     RG + "test_python_codec_registration", "Python hook returning Written, OutputBundle or (OutputBundle, report)")
rule("fontpixel::formats::FormatWriter::transport_limits", "adapted", "writer.transport_limits() -> TransportLimits dict",
     RG + "test_python_codec_registration", "optional method of a Python writer object")
rule("fontpixel::formats::FormatWriter::validate_transport", "adapted", "writer.validate_transport(font_set, options, limits)",
     RG + "test_python_codec_registration", "optional method of a Python writer object, run for gzip output")
for name in ("common_transport_limits", "write_owned", "write_reserved", "validate_transport_reserved"):
    rule(f"fontpixel::formats::FormatWriter::{name}", "adapted", f"Rust default of FormatWriter::{name} for Python writers",
         RG + "test_python_codec_registration",
         "provided trait method; Python writers keep the Rust default (borrowed route, intersected limits), "
         "which Registry.write/write_owned/write_reserved_with_report run")
rule("fontpixel::formats::Loaded", "bound", "fontpixel.Loaded (fonts, report, format)", RG + "test_read_matches_cli_and_reports")
rule("fontpixel::formats::Loaded::into_single", "bound", "fontpixel.Loaded.into_single", RG + "test_read_matches_cli_and_reports")
rule("fontpixel::formats::OwnedWrite", "adapted", "Registry.write_owned result (Written)", RG + "test_write_variants_agree_and_owned_moves_the_model",
     "internal writer protocol enum; the owned route is reached through Registry.write_owned and never surfaces")
rule("fontpixel::formats::ReadOptions", "adapted", "format=/limits= arguments of read; normalize('formats::ReadOptions')",
     OP + "test_option_type_round_trips_and_rejects_unknown", "serde plain data; its fields are keyword arguments of read and the dict given to Python reader hooks")
rule("fontpixel::formats::WriteOptions", "adapted", "primary_name=/strict=/transport_limits= arguments of write",
     RG + "test_write_strict_mode_and_reports", "serde plain data; its fields are keyword arguments of write and the dict given to Python writer hooks")
rule("fontpixel::formats::WriteOptions::new", "adapted", "write(..., primary_name=...)", RG + "test_transport_limits_and_gzip_envelope",
     "constructor of the keyword arguments; the default primary name is font.<first extension>")
rule("fontpixel::formats::Registration", "adapted", "Registry.register(format, detector=, reader=, writer=)",
     RG + "test_python_codec_registration", "holds boxed trait objects; built on the Rust side from Python hooks")
rule("fontpixel::formats::Registration::planned", "adapted", "Registry.register(format) without hooks",
     RG + "test_python_codec_registration", "a registration without hooks is the planned entry")
rule("fontpixel::formats::Registration::status", "adapted", "Registry.status(id)", RG + "test_python_codec_registration",
     "status of a registered entry is read back through the registry")
rule("fontpixel::formats::Registry", "bound", "fontpixel.Registry", RG + "test_registry_formats_status_and_names")
rule("fontpixel::formats::Registry::new", "adapted", "fontpixel.Registry(builtin=False)", RG + "test_planned_registry_has_no_codecs",
     "Registry() is fontpixel::registry(); builtin=False is the planned catalogue of Registry::new")
REG_TESTS = {
    "detect": "test_detect_content_then_name_hint",
    "ensure_writable": "test_planned_registry_has_no_codecs",
    "extension_candidates": "test_registry_formats_status_and_names",
    "format_from_name": "test_registry_formats_status_and_names",
    "formats": "test_registry_formats_status_and_names",
    "read": "test_sidecar_formats_with_every_resource_kind",
    "register": "test_python_codec_registration",
    "status": "test_registry_formats_status_and_names",
    "write": "test_write_variants_agree_and_owned_moves_the_model",
    "write_owned": "test_write_variants_agree_and_owned_moves_the_model",
    "write_reserved_with_report": "test_write_variants_agree_and_owned_moves_the_model",
    "write_with_report": "test_write_strict_mode_and_reports",
}
for name, test in REG_TESTS.items():
    rule(f"fontpixel::formats::Registry::{name}", "bound", f"fontpixel.Registry.{name}", RG + test)
rule("fontpixel::formats::Registry::set_*_options", "bound", "fontpixel.Registry.{name} (also set_read_options/set_write_options by format id)",
     OP + "test_typed_setter_accepts_defaults_and_rejects_unknown")

# --- per-module -----------------------------------------------------------
EXTRA = {
    "embedded::write_color": ("fontpixel.formats.embedded.write_color", EX + "test_embedded_codecs"),
    "embedded::EmbeddedCodec::new": ("fontpixel.formats.embedded.codec", EX + "test_embedded_codecs"),
    "embedded::metadata::EmbeddedMetadataOptions::validate": ("fontpixel.formats.embedded.validate_metadata", EX + "test_embedded_codecs"),
    "embedded::metadata::EmbeddedMetadataOptions::retained_bytes": ("fontpixel.formats.embedded.metadata_retained_bytes", EX + "test_embedded_codecs"),
    "fbit::read_context": ("fontpixel.formats.fbit.read_context", EX + "test_fnt_fbit_nfnt_hanfont_hzk_raw_helpers"),
    "fbit::write_bundle": ("fontpixel.formats.fbit.write_bundle", EX + "test_fnt_fbit_nfnt_hanfont_hzk_raw_helpers"),
    "fnt::charset_name": ("fontpixel.formats.fnt.charset_name", EX + "test_fnt_fbit_nfnt_hanfont_hzk_raw_helpers"),
    "fnt::read_default": ("fontpixel.formats.fnt.read_default", EX + "test_fnt_fbit_nfnt_hanfont_hzk_raw_helpers"),
    "hanfont::component_slots": ("fontpixel.formats.hanfont.component_slots", EX + "test_fnt_fbit_nfnt_hanfont_hzk_raw_helpers"),
    "nfnt::writer::write_bundle": ("fontpixel.formats.nfnt.write_bundle", EX + "test_fnt_fbit_nfnt_hanfont_hzk_raw_helpers"),
    "hzk::presets::Preset::ALL": ("fontpixel.formats.hzk.presets()", EX + "test_fnt_fbit_nfnt_hanfont_hzk_raw_helpers"),
    "hzk::presets::Preset::geometry": ("fontpixel.formats.hzk.preset_geometry", EX + "test_fnt_fbit_nfnt_hanfont_hzk_raw_helpers"),
    "hzk::presets::Preset::name": ("fontpixel.formats.hzk.preset_name", EX + "test_fnt_fbit_nfnt_hanfont_hzk_raw_helpers"),
    "raw::RawLayout::new": ("fontpixel.formats.raw.raw_layout", EX + "test_fnt_fbit_nfnt_hanfont_hzk_raw_helpers"),
    "raw::RawPreset::layout": ("fontpixel.formats.raw.preset_layout", EX + "test_fnt_fbit_nfnt_hanfont_hzk_raw_helpers"),
    "svg::writer::glyph_image": ("fontpixel.formats.svg.glyph_image", EX + "test_svg_image_helpers"),
    "svg::writer::image": ("fontpixel.formats.svg.image", EX + "test_svg_image_helpers"),
    "svg::writer::path_data": ("fontpixel.formats.svg.path_data", EX + "test_svg_image_helpers"),
    "vector_raster::Codec::new": ("fontpixel.formats.vector_raster.codec", EX + "test_vector_raster_helpers"),
    "vector_raster::detect_native_ppem": ("fontpixel.formats.vector_raster.detect_native_ppem", EX + "test_vector_raster_helpers"),
    "vector_raster::write_owned": ("fontpixel.formats.vector_raster.write_owned", EX + "test_vector_raster_helpers"),
    "x11::source_rows": ("fontpixel.formats.x11.source_rows (also fontpixel.formats.bdf.source_rows)", EX + "test_x11_source_rows_and_validation"),
    "x11::validate_bitmap": ("fontpixel.formats.x11.validate_bitmap (also fontpixel.formats.bdf.validate_bitmap)", EX + "test_x11_source_rows_and_validation"),
}
ADAPTED_EXTRA = {
    "hzk::presets::Preset::ALL": "associated constant exposed as a function returning the preset names",
}
mods = sorted({i["path"].split("::")[2] for i in mine if i["path"].count("::") >= 3})
SHARED = {"tex_common": "pk and gf", "w5a1_common": "dosstart, drhalo, edwin, mkwinfont, pcr, plus3dos, psf2txt and writeon",
          "w5a2_common": "bbc, comfont, consoleet, grasp, hrcg, wyse, xbin and zapfont"}
for m in mods:
    if m in ("Registry", "FormatWriter", "FormatDetector", "FormatReader", "Loaded", "Registration", "WriteOptions"):
        continue
    if m == "catalogue":
        rule("fontpixel::formats::catalogue", "adapted", "fontpixel.formats.CATALOGUE", EX + "test_catalogue_constant",
             "the catalogue module's only item is the CATALOGUE constant")
        rule("fontpixel::formats::catalogue::CATALOGUE", "bound", "fontpixel.formats.CATALOGUE", EX + "test_catalogue_constant")
        continue
    if m in SHARED:
        rule(f"fontpixel::formats::{m}", "adapted", f"option dicts of {SHARED[m]}", OP + "test_option_type_round_trips_and_rejects_unknown",
             f"crate-private module whose option types are re-exported by {SHARED[m]}; exposed through those formats' option dicts")
        rule(f"fontpixel::formats::{m}::**", "adapted", f"option dicts of {SHARED[m]} (fontpixel.formats.normalize)",
             OP + "test_option_type_round_trips_and_rejects_unknown",
             "plain data through serde: dicts with the Rust field names, unknown keys rejected")
        continue
    rule(f"fontpixel::formats::{m}", "bound", f"fontpixel.formats.{m}", EX + "test_namespaces_are_importable_modules")
    rule(f"fontpixel::formats::{m}::**", "adapted",
         f"dicts/strings: fontpixel.formats.normalize('formats::{m}::<Type>'), Registry.set_*_options, Registry.set_codec",
         OP + "test_option_type_round_trips_and_rejects_unknown",
         "plain data through serde: option/codec structs and enums are dicts and strings with the Rust names, unknown keys rejected")
    for i in mine:
        p = i["path"]
        if not p.startswith(f"fontpixel::formats::{m}::"):
            continue
        rel = p[len("fontpixel::formats::"):]
        last = rel.split("::")[-1]
        if i["kind"] == "function" and last in ("read", "write", "detect") and rel not in EXTRA:
            if m == "embedded":
                test = EX + "test_embedded_codecs"
            elif m == "vector_raster":
                test = EX + "test_vector_raster_helpers"
            else:
                test = RT + "test_direct_namespace_matches_registry"
            rule(p, "bound", f"fontpixel.formats.{m}.{last}", test)
        elif rel in EXTRA:
            py, test = EXTRA[rel]
            if rel in ADAPTED_EXTRA:
                rule(p, "adapted", py, test, ADAPTED_EXTRA[rel])
            else:
                rule(p, "bound", py, test)
        elif rel == "vector_raster::Codec":
            rule(p, "adapted", "fontpixel.formats.vector_raster.codec(format); Registry.set_vector_read_options/set_vector_write_options",
                 EX + "test_vector_raster_helpers",
                 "codec handle holding a &'static format id; its options are dicts and codec(format) returns its defaults")
        elif i["kind"] in ("function", "method", "assoc_const", "constant", "trait", "trait_item"):
            unclassified(p, "no binding entry")
        elif i["kind"] in ("struct", "enum") and "Deserialize" not in i.get("serde", []):
            unclassified(p, "falls to the serde catch-all but does not derive Deserialize")
        elif i["kind"] in ("struct", "enum") and f'"{p[len("fontpixel::"):]}"' not in normalize_rows:
            unclassified(p, "missing from formats_types.rs; run tools/bindings/gen_formats_types.py")

explicit = {r["pattern"] for r in rules if "*" not in r["pattern"]}


def needed(r):
    if not r["pattern"].endswith("::**"):
        return True
    prefix = r["pattern"][:-2]
    return any(p.startswith(prefix) and p not in explicit for p in PATHS)


rules = [r for r in rules if needed(r)]
out = ["# Format registry, codecs and per-format options — unit p2 (Python).",
       "# Generated by tools/bindings/gen_formats_coverage.py from the rustdoc inventory;",
       "# do not edit by hand. Rule syntax: tools/bindings/check.py.", ""]
for r in rules:
    out.append("[[rule]]")
    for k in ("pattern", "status", "python", "python_test", "reason", "evidence"):
        if k in r:
            out.append(f"{k} = {json.dumps(r[k], ensure_ascii=False)}")
    out.append("")
text = "\n".join(out)
if ARGS.check:
    if (OUT.read_text() if OUT.exists() else "") != text:
        print(f"{OUT.relative_to(ROOT)} is out of date; run tools/bindings/gen_formats_coverage.py",
              file=sys.stderr)
        sys.exit(1)
    print(f"{OUT.relative_to(ROOT)} up to date ({len(rules)} rules)")
else:
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)} ({len(rules)} rules)")
