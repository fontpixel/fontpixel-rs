#!/usr/bin/env python3
"""Generate the Python API reference (docs/python-api-reference.md).

Lists every public module, class, function, method, property and constant of
the installed `fontpixel` package (tools/bindings/pyapi.py) with its typed
signature and docstring. Signatures of native objects come from the
generated stubs (`python/fontpixel/**/*.pyi`, parsed with `ast`), so the
reference shows the same types a type checker sees; pure-Python objects use
their inline annotations. The module index between the
`<!-- reference index -->` markers of docs/python-api.md is regenerated too.

Usage (with the extension installed):
    tools/bindings/gen_pyref.py [--check]

`--check` writes nothing and exits 1 when a committed file differs.
"""
from __future__ import annotations

import argparse
import ast
import inspect
import sys
import types
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
PKG = ROOT / "crates/fontpixel-py/python/fontpixel"
REFERENCE = ROOT / "docs/python-api-reference.md"
GUIDE = ROOT / "docs/python-api.md"
BEGIN, END = "<!-- reference index: generated by tools/bindings/gen_pyref.py -->", "<!-- end reference index -->"
sys.path.insert(0, str(HERE))

import pyapi  # noqa: E402

KIND_LABEL = {"module": "module", "class": "class", "exception": "exception", "function": "function",
              "method": "method", "staticmethod": "static method", "classmethod": "class method",
              "property": "property", "constant": "constant", "alias": "class"}


# ------------------------------------------------------------------ stub signatures

class StubIndex:
    """Typed signatures from the generated `.pyi` files, keyed by runtime object."""

    def __init__(self):
        import gen_pyi
        self.by_id = {}
        mods = gen_pyi.native_modules()
        for dotted, (mod, rel) in mods.items():
            tree = ast.parse((PKG / rel).read_text())
            defs = {}
            for node in tree.body:
                if isinstance(node, ast.FunctionDef):
                    defs[node.name] = node
                elif isinstance(node, ast.ClassDef):
                    for sub in node.body:
                        if isinstance(sub, ast.FunctionDef):
                            defs.setdefault(f"{node.name}.{sub.name}", sub)
                elif isinstance(node, ast.AnnAssign) and isinstance(node.target, ast.Name):
                    defs[node.target.id] = node
            for attr, value in vars(mod).items():
                if attr in defs:
                    self.by_id[id(value)] = defs[attr]
                if isinstance(value, type):
                    for member, raw in vars(value).items():
                        key = f"{attr}.{member}"
                        if key in defs:
                            self.by_id[(id(value), member)] = defs[key]
                    if f"{attr}.__new__" in defs:
                        self.by_id[(id(value), "__new__")] = defs[f"{attr}.__new__"]

    def signature(self, entry, owner=None):
        node = None
        if owner is not None:
            node = self.by_id.get((id(owner), entry.name.rsplit(".", 1)[1]))
        elif entry.kind in ("class",):
            node = self.by_id.get((id(entry.obj), "__new__"))
        else:
            node = self.by_id.get(id(entry.obj))
        if isinstance(node, ast.AnnAssign):
            return ": " + ast.unparse(node.annotation)
        if not isinstance(node, ast.FunctionDef):
            return None
        args = node.args
        params = []
        decorators = {ast.unparse(d) for d in node.decorator_list}
        positional = args.posonlyargs + args.args
        skip_first = positional and positional[0].arg in ("self", "cls") and "staticmethod" not in decorators
        defaults = [None] * (len(positional) - len(args.defaults)) + list(args.defaults)
        for i, (a, d) in enumerate(zip(positional, defaults)):
            if i == 0 and skip_first:
                continue
            text = a.arg + (": " + ast.unparse(a.annotation) if a.annotation else "")
            params.append(text + (" = ..." if d is not None else ""))
            if args.posonlyargs and a is args.posonlyargs[-1]:
                params.append("/")
        if args.vararg:
            params.append("*" + args.vararg.arg + (": " + ast.unparse(args.vararg.annotation)
                                                   if args.vararg.annotation else ""))
        elif args.kwonlyargs:
            params.append("*")
        for a, d in zip(args.kwonlyargs, args.kw_defaults):
            text = a.arg + (": " + ast.unparse(a.annotation) if a.annotation else "")
            params.append(text + (" = ..." if d is not None else ""))
        if args.kwarg:
            params.append("**" + args.kwarg.arg + (": " + ast.unparse(args.kwarg.annotation)
                                                   if args.kwarg.annotation else ""))
        ret = " -> " + ast.unparse(node.returns) if node.returns else ""
        if "property" in decorators or any(d.endswith(".setter") for d in decorators):
            return ret.replace(" -> ", ": ")
        return "(" + ", ".join(params) + ")" + ret


def clean(text):
    """Strip the `_t.`/`_c.`/`_b.` module aliases the stubs use."""
    for prefix in ("_t.", "_c.", "_b.", "_types."):
        text = text.replace(prefix, "")
    return text


# ------------------------------------------------------------------ rendering

def anchor(name):
    return name.lower().replace(".", "")


def render():
    stubs = StubIndex()
    entries = list(pyapi.walk())
    owners = {e.name: e.obj for e in entries if e.kind in ("class", "exception")}
    out = ["# fontpixel Python API reference", "",
           "<!-- Generated by tools/bindings/gen_pyref.py; do not edit by hand. -->", "",
           "Every public module, class, function, method, property and constant of the",
           "`fontpixel` package with its typed signature (as in the bundled type stubs) and",
           "docstring. Plain-data shapes (`FontMetrics`, `RenderOptions`, `PcfWriteOptions`,",
           "...) are the `TypedDict`s and `Literal` aliases of `fontpixel.types`; see",
           "[python-api.md](python-api.md) for the concepts and how to discover option",
           "shapes at run time.", ""]
    counts = {}
    modules = [e for e in entries if e.kind == "module"]
    out.append("## Modules")
    out.append("")
    by_module = {}
    for e in entries:
        if e.kind == "module":
            by_module[e.name] = []
            current = e.name
        else:
            by_module[current].append(e)
    for m in modules:
        n = len([e for e in by_module[m.name] if e.kind not in ("constant", "alias")])
        counts[m.name] = n
        summary = m.doc.split("\n\n")[0].replace("\n", " ") if m.doc else ""
        out.append(f"- [`{m.name}`](#{anchor(m.name)}) ({n}) {summary}")
    out.append("")
    for m in modules:
        out.append(f"## {m.name}")
        out.append("")
        if m.doc:
            out.append(m.doc)
            out.append("")
        for e in by_module[m.name]:
            owner_name = e.name.rsplit(".", 1)[0]
            owner = owners.get(owner_name) if e.kind in ("method", "staticmethod", "classmethod", "property") else None
            sig = stubs.signature(e, owner)
            if sig is None:
                sig = e.signature if e.kind not in ("property", "constant", "alias") else ""
                if e.kind == "constant":
                    sig = ": " + type(e.obj).__name__
            sig = clean(sig)
            level = "###" if e.kind in ("class", "exception", "function", "alias") or e.kind == "constant" \
                and owner_name == m.name else "####"
            label = KIND_LABEL[e.kind]
            if e.kind == "exception":
                bases = ", ".join(b.__name__ for b in e.obj.__bases__)
                sig = f"({bases})"
            out.append(f"{level} `{e.name}{sig}`")
            out.append("")
            out.append(f"*{label}*" + (f" -- {e.doc}" if e.doc and "\n" not in e.doc and len(e.doc) < 100 else ""))
            if e.doc and ("\n" in e.doc or len(e.doc) >= 100):
                out.append("")
                out.append(e.doc)
            out.append("")
    reference = "\n".join(out).rstrip() + "\n"
    index = [BEGIN, "", "| module | public callables |", "| --- | ---: |"]
    for m in modules:
        index.append(f"| [`{m.name}`](python-api-reference.md#{anchor(m.name)}) | {counts[m.name]} |")
    total = sum(1 for e in entries if e.kind not in ("module", "constant", "alias"))
    index += ["", f"{len(modules)} modules, {total} documented callables, classes and properties.", "", END]
    return reference, "\n".join(index)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args(argv)
    reference, index = render()
    guide = GUIDE.read_text()
    if BEGIN not in guide or END not in guide:
        print(f"{GUIDE.relative_to(ROOT)} lacks the reference index markers", file=sys.stderr)
        return 1
    start, end = guide.index(BEGIN), guide.index(END) + len(END)
    new_guide = guide[:start] + index + guide[end:]
    if args.check:
        bad = [p for p, text in ((REFERENCE, reference), (GUIDE, new_guide))
               if not p.exists() or p.read_text() != text]
        for p in bad:
            print(f"out of date: {p.relative_to(ROOT)} (run tools/bindings/gen_pyref.py)", file=sys.stderr)
        return 1 if bad else 0
    REFERENCE.write_text(reference)
    GUIDE.write_text(new_guide)
    return 0


if __name__ == "__main__":
    sys.exit(main())
