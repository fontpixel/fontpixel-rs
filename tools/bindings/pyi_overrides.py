def _match(table, key):
    if key in table:
        return table[key]
    best = None
    for pat, val in table.items():
        if any(ch in pat for ch in "*?[") and fnmatch.fnmatchcase(key, pat):
            if best is None or len(pat) > len(best[0]):
                best = (pat, val)
    return best[1] if best else None


def lookup(table, qual, item=None):
    entry = _match(table, qual)
    if entry is None:
        return None
    if item is None:
        return entry
    if isinstance(entry, dict):
        return entry.get(item)
    return entry if item == "return" else None


def param_rule(qual, name):
    module = qual
    for pat, rules in PARAMS.items():
        if fnmatch.fnmatchcase(module, pat + ".*") or fnmatch.fnmatchcase(module, pat) or pat == "*":
            if name in rules:
                return rules[name]
    return None


def explicit_any(key):
    return any(fnmatch.fnmatchcase(key, pat) for pat in EXPLICIT_ANY)


