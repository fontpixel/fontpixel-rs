"""Type information gen_pyi.py cannot derive by itself.

Everything else (names, parameter kinds/defaults, docstrings, the Rust
parameter and result types, the serde shapes) is derived; this file only
covers what is invisible to the scanner:

* ``HELPERS`` -- the Python type a ``*_arg`` conversion helper accepts;
* ``RUST_TYPES`` -- Python types of Rust types that are not serde shapes;
* ``PARAMS`` -- parameter-name rules per module glob for ``&Bound<PyAny>``
  parameters converted without a typed ``let`` (first matching glob wins);
* ``SIGNATURES`` -- per-callable parameter/result types (``fnmatch`` globs
  allowed; the most specific key wins): results built from ``PyAny``, and the
  functions generated by ``macro_rules!`` (codec namespaces, registry
  setters);
* ``EXCEPTION_ATTRS`` -- attributes set on raised exceptions;
* ``EXPLICIT_ANY`` -- places where ``Any`` is the honest type (arbitrary
  caller objects), so they are not reported as untyped.

Type expressions use ``_t.`` for ``fontpixel.types`` names, ``_c.`` for
``collections.abc`` and ``@module.Class`` for binding classes (resolved to
imports by the generator).
"""
