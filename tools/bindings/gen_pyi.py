class Imports:
    def __init__(self, module_name):
        self.module = module_name
        self.local = set()
        self.refs = {}       # local alias -> (module, name)

    def ref(self, module, name):
        if module == self.module:
            return name
        alias = name
        if alias in self.local or (alias in self.refs and self.refs[alias] != (module, name)):
            alias = "_" + module.split(".")[-1].lstrip("_") + "_" + name
        self.refs[alias] = (module, name)
        return alias


class Renderer:
    def __init__(self, model, typer, home):
        self.model = model
        self.typer = typer
        self.home = home     # id(class) -> (stub module name, class name)
        self.allow = {k: list(v) for k, v in ovr.STUBTEST_ALLOW.items()}

    def stub_module_of(self, runtime_module):
        """Module name used in imports for classes defined in `runtime_module`."""
        return runtime_module

    def resolve_refs(self, text, imp):
        """Turn `@module.Class` markers into imported local names."""
        def sub(m):
            full = m.group(1)
            mod, _, name = full.rpartition(".")
            mod = {"fontpixel": "fontpixel._native",
                   "fontpixel.compat.bdfparser": "fontpixel._native._bdfparser",
                   "fontpixel.ops": "fontpixel._native._ops"}.get(mod, mod)
            return imp.ref(mod, name)
        return re.sub(r"@([\w.]+)", sub, text)

    def render(self, m):
        imp = Imports(m.name)
        imp.local = {c.name for c in m.classes} | {f.name for f in m.functions} | {n for n, _ in m.constants}
        body = []
        for attr, target in m.submodules:
            body.append(("submodule", attr, target))
        lines = []
        for c in sorted(m.classes, key=lambda c: (not c.exception, c.name)):
            lines += self.render_class(m, c, imp)
            lines.append("")
        for f in m.functions:
            lines += self.render_function(m, None, f, imp)
            lines.append("")
        for name, value in m.constants:
            t = self.typer_const(m, name, value)
            lines.append(f"{name}: {self.resolve_refs(t, imp)}")
        doc = m.doc
        out = [HEADER]
        if doc:
            out.append(docstring(doc, 0))
        out.append("from __future__ import annotations\n")
        out.append("import collections.abc as _c")
        out.append("import builtins as _b")
        out.append("import types as _types")
        out.append("from typing import Any, Literal, final, overload")
        out.append("")
        out.append("from typing_extensions import Self, disjoint_base")
        out.append("")
        out.append("from fontpixel import types as _t")
        if m.name == "fontpixel._native":
            out.append("from fontpixel._native import _bdfparser as _bdfparser")
            out.append("from fontpixel._native import _ops as _ops")
        for attr, target in m.submodules:
            parent, _, leaf = target.rpartition(".")
            if leaf == attr:
                out.append(f"from {parent} import {leaf} as {leaf}")
            else:
                out.append(f"import {target} as {attr}")
        refs = {}
        for alias, (mod, name) in sorted(imp.refs.items()):
            refs.setdefault(mod, []).append((name, alias))
        for mod in sorted(refs):
            names = ", ".join(n if n == a else f"{n} as {a}" for n, a in sorted(refs[mod]))
            out.append(f"from {mod} import {names}")
        out.append("")
        runtime_all = getattr(m.obj, "__all__", None)
        if runtime_all is not None:
            out.append("__all__ = [")
            out += [f"    {json.dumps(n)}," for n in runtime_all]
            out.append("]")
            out.append("")
        text = "\n".join(out) + "\n" + "\n".join(lines).rstrip() + "\n"
        return text

    def typer_const(self, m, name, value):
        key = f"{m.name}.{name}"
        t = ovr.lookup(ovr.CONSTANTS, key)
        if t:
            return t
        return value_type(value)

    BUILTIN_TYPES = ("bytes", "list", "dict", "str", "int", "float", "bool", "set", "tuple", "type",
                     "frozenset", "bytearray", "object")

    def shadow(self, t, c):
        """Qualify builtin type names that a class member of the same name
        would shadow inside the class body (`ReadContext.bytes`)."""
        if c is None:
            return t
        names = {mm.name for mm in c.members}
        for b in self.BUILTIN_TYPES:
            if b in names:
                t = re.sub(rf"(?<![\w.]){b}\b", f"_b.{b}", t)
        return t

    def render_class(self, m, c, imp):
        cls_ref = c.name
        if c.exception:
            bases = []
            for b in c.bases:
                if b.__module__ == "builtins":
                    bases.append(b.__name__)
                else:
                    home = self.typer.class_home.get(id(b))
                    bases.append(imp.ref(*home) if home and home[0] != m.name else (home[1] if home else b.__name__))
            lines = [f"class {c.name}({', '.join(bases)}):"]
            if c.doc:
                lines.append(docstring(c.doc, 4))
            attrs = ovr.lookup(ovr.EXCEPTION_ATTRS, c.qual) or {}
            for a, t in attrs.items():
                lines.append(f"    {a}: {self.resolve_refs(t, imp)}")
            if not c.doc and not attrs:
                lines.append("    ...")
            return lines
        bases = [b.__name__ for b in c.bases]
        head = f"class {c.name}({', '.join(bases)}):" if bases else f"class {c.name}:"
        lines = []
        # Native classes own their instance layout (`@disjoint_base`); pyo3
        # classes without `subclass` cannot be subclassed (`@final`).
        if not c.obj.__flags__ & (1 << 10):
            lines.append("@final")
        elif not bases:
            lines.append("@disjoint_base")
        lines.append(head)
        if c.doc:
            lines.append(docstring(c.doc, 4))
        body = []
        for mm in c.members:
            body += self.render_member(m, c, mm, imp)
        if not body and not c.doc:
            body.append("    ...")
        return lines + body

    def render_member(self, m, c, mm, imp):
        typer = self.typer
        if mm.kind == "unhashable":
            return ["    __hash__: None  # type: ignore[assignment]"]
        if mm.kind == "classattr":
            t = ovr.lookup(ovr.CONSTANTS, mm.qual) or value_type(mm.obj)
            return [f"    {mm.name}: {self.resolve_refs(t, imp)}"]
        if mm.kind == "property":
            typer.counts["properties"] += 1
            rust = typer.rust_for(m.name, c, Callable_(mm.qual, mm.name, "getter", [], mm.doc))
            setter = typer.setter_for(c, mm.name)
            t = ovr.lookup(ovr.SIGNATURES, mm.qual, "return")
            if t is None and rust is not None:
                t = typer.rust_type(rust.ret, "return", c.name)
            if t is None:
                rc = typer.rust_class_of(c)
                field_t = next((f for f in (rc.fields if rc else []) if f[0] == mm.name), None)
                if field_t:
                    t = typer.rust_type(field_t[1], "return", c.name)
            if has_any(t):
                if not ovr.explicit_any(mm.qual):
                    typer.counts["properties_any"] += 1
                    typer.unresolved.append(f"{mm.qual} -> {t}")
                t = t or "Any"
            t = self.shadow(self.resolve_refs(t, imp), c)
            lines = ["    @property", f"    def {mm.name}(self) -> {t}:"]
            lines.append(docstring(mm.doc, 8) if mm.doc else "        ...")
            if mm.doc:
                lines[-1] += ""
            if setter is not None:
                st = ovr.lookup(ovr.SIGNATURES, mm.qual, "set")
                if st is None:
                    params = setter.params
                    st = typer.rust_type(params[0][1], "param", c.name, setter.hints.get(params[0][0])) if params else t
                    if st == "Any" and t != "Any":
                        st = t
                st = self.shadow(self.resolve_refs(st, imp), c)
                lines += [f"    @{mm.name}.setter", f"    def {mm.name}(self, value: {st}) -> None: ..."]
            return lines
        rust = typer.rust_for(m.name, c, mm)
        rc = typer.rust_class_of(c)
        if mm.name in ("__lt__", "__le__", "__gt__", "__ge__") and rust is None and rc is not None \
                and "ord" not in rc.options:
            # pyo3 fills the whole rich-comparison slot for `__eq__`; ordering
            # then returns NotImplemented, so the stub leaves it out.
            return []
        partner = PHANTOM_PARTNERS.get(mm.name)
        if rust is None and rc is not None and partner and typer.methods.get((rc.rust_name, partner, "other")):
            # pyo3 fills both halves of a slot; the half the class does not
            # implement only raises (`del x[i]`) or returns NotImplemented.
            # stubtest reports the missing reflected operators only.
            if not mm.name.startswith("__r"):
                return []
            self.allow.setdefault(
                "pyo3 companion slot wrappers the class does not implement (they raise "
                "or return NotImplemented), left out so type checkers reject them", []).append(
                rf"fontpixel(\..+)?\.{c.name}\.{mm.name}")
            return []
        return self.render_function(m, c, mm, imp, rust)

    def render_function(self, m, c, f, imp, rust=None):
        typer = self.typer
        if rust is None and c is None:
            rust = typer.rust_for(m.name, None, f)
        if f.kind == "new" and not f.doc and rust is not None:
            f.doc = inspect.cleandoc(rust.doc)
        indent = "    " if c else ""
        cls_name = c.name if c else None
        params = list(f.params)
        if c is not None and f.kind in ("method",) and params and params[0].name in ("self", "$self"):
            params = params[1:]
        if c is not None and f.kind in ("classmethod", "new") and params and params[0].name in ("cls", "$cls", "$type"):
            params = params[1:]
        rendered = []
        rmap = dict(rust.params) if rust else {}
        if rust and f.name.startswith("__") and len(rust.params) == len(params):
            # Slot wrappers name their parameters (`key`, `value`) differently.
            rmap = {p.name: rp[1] for p, rp in zip(params, rust.params)}
            rust = _renamed_hints(rust, params)
        seen_kw = False
        saw_posonly = any(p.kind == "positional_only" for p in params)
        for p in params:
            t = self.param_type(f, p, rust, rmap, cls_name)
            t = self.shadow(self.resolve_refs(t, imp), c)
            if p.kind == "var_positional":
                rendered.append(f"*{p.name}: {t}")
                seen_kw = True
                continue
            if p.kind == "var_keyword":
                rendered.append(f"**{p.name}: {t}")
                continue
            if p.kind == "keyword_only" and not seen_kw:
                rendered.append("*")
                seen_kw = True
            default = " = ..." if p.has_default else ""
            rendered.append(f"{p.name}: {t}{default}")
            if p.kind == "positional_only" and saw_posonly and (
                    params.index(p) == len(params) - 1 or params[params.index(p) + 1].kind != "positional_only"):
                rendered.append("/")
        ret = self.return_type(f, rust, cls_name)
        ret = self.shadow(self.resolve_refs(ret, imp), c)
        lines = []
        name = f.name
        if f.kind == "static":
            lines.append(f"{indent}@staticmethod")
            args = ", ".join(rendered)
        elif f.kind == "classmethod":
            lines.append(f"{indent}@classmethod")
            args = ", ".join(["cls"] + rendered)
        elif f.kind == "new":
            args = ", ".join(["cls"] + rendered)
        elif c is not None:
            args = ", ".join(["self"] + rendered)
        else:
            args = ", ".join(rendered)
        head = f"{indent}def {name}({args}) -> {ret}:"
        if len(head) > 100:
            inner = (",\n" + indent + "    ").join((["cls"] if f.kind in ("new", "classmethod") else ["self"] if c is not None and f.kind != "static" else []) + rendered)
            head = f"{indent}def {name}(\n{indent}    {inner},\n{indent}) -> {ret}:"
        lines.append(head)
        lines.append(docstring(f.doc, len(indent) + 4) if f.doc else f"{indent}    ...")
        return lines

    def param_type(self, f, p, rust, rmap, cls_name):
        typer = self.typer
        typer.counts["params"] += 1
        if f.name in ("__eq__", "__ne__"):
            return "object"
        t = ovr.lookup(ovr.SIGNATURES, f.qual, p.name)
        if t is None and p.kind == "var_keyword":
            return "Any"
        if t is None and rust is None:
            t = (typer.macro_sig(f) or {}).get(p.name)
        if t is None and rust is not None and p.name in rmap:
            with typer.in_file(rust.file):
                t = typer.rust_type(rmap[p.name], "param", cls_name, rust.hints.get(p.name))
                casts = rust.casts.get(p.name, [])
                if casts and p.name in rust.hints and not has_any(t):
                    # `obj.cast::<PyFont>()` first, then a serde/helper conversion.
                    for cast in casts:
                        if typer.binding_class(cast):
                            t = union(typer.class_ref(typer.py_of_rust[cast]), t)
            if "Any" in split_union(t):
                alt = ovr.param_rule(f.qual, p.name)
                if alt:
                    t = alt if not t.endswith("| None") else union(alt, "None")
        if t is None:
            t = ovr.param_rule(f.qual, p.name)
        if t is None and p.kind == "var_keyword":
            t = "Any"
        if t is None and p.name in ("_memo", "memo"):
            t = "Any"
        if has_any(t):
            if not (ovr.explicit_any(f.qual + ":" + p.name) or p.kind == "var_keyword" or p.name in ("memo", "_memo")):
                typer.counts["params_any"] += 1
                typer.unresolved.append(f"{f.qual}({p.name}) -> {t}")
            t = t or "Any"
        if p.has_default and p.default is None and "None" not in split_union(t) and t != "Any":
            t = union(t, "None")
        return t

    def return_type(self, f, rust, cls_name):
        typer = self.typer
        if f.kind == "new":
            return cls_name
        typer.counts["returns"] += 1
        t = ovr.lookup(ovr.SIGNATURES, f.qual, "return")
        if t is None and rust is None:
            t = (typer.macro_sig(f) or {}).get("return")
        if t is None and rust is not None:
            with typer.in_file(rust.file):
                t = typer.rust_type(rust.ret, "return", cls_name)
                if "Any" in split_union(t):
                    alt = typer.ret_hint_type(rust.ret_hint)
                    if alt and rust.bytes_fields and re.fullmatch(r"_t\.\w+", alt):
                        alt = typer.bytes_view(alt[3:], rust.bytes_fields)
                    if alt:
                        t = union(alt, "None") if "None" in split_union(t) else alt
        if t is None and f.name in DUNDER_RETURNS:
            t = DUNDER_RETURNS[f.name]
        if has_any(t):
            if not ovr.explicit_any(f.qual + ":return"):
                typer.counts["returns_any"] += 1
                typer.unresolved.append(f"{f.qual} -> {t}")
            t = t or "Any"
        return t


PHANTOM_PARTNERS = {"__delitem__": "__setitem__", "__setitem__": "__delitem__",
                    "__radd__": "__add__", "__rsub__": "__sub__", "__rmul__": "__mul__",
                    "__rmatmul__": "__matmul__", "__ror__": "__or__", "__rand__": "__and__",
                    "__rxor__": "__xor__"}


def _renamed_hints(rust, params):
    """A copy of `rust` whose parameter names/hints follow the runtime names."""
    import copy
    r = copy.copy(rust)
    names = {rp[0]: p.name for p, rp in zip(params, rust.params)}
    r.params = [(names[n], t) for n, t in rust.params]
    r.hints = {names.get(k, k): v for k, v in rust.hints.items()}
    r.casts = {names.get(k, k): v for k, v in rust.casts.items()}
    return r


def qualify_serde(expr, serde):
    """Prefix serde type names in a serde_shapes type expression with `_t.`."""
    names = set(serde.names.values()) | {"SerdeBytes", "StrPath"}
    return re.sub(r"(?<![\w.])([A-Z]\w*)", lambda m: "_t." + m.group(1) if m.group(1) in names else m.group(1), expr)


DUNDER_RETURNS = {"__len__": "int", "__bool__": "bool", "__int__": "int", "__index__": "int",
                  "__hash__": "int", "__eq__": "bool", "__ne__": "bool", "__lt__": "bool",
                  "__le__": "bool", "__gt__": "bool", "__ge__": "bool", "__contains__": "bool",
                  "__bytes__": "bytes"}


def value_type(value):
    if isinstance(value, bool):
        return "bool"
    if isinstance(value, int):
        return "int"
    if isinstance(value, float):
        return "float"
    if isinstance(value, str):
        return "str"
    if isinstance(value, bytes):
        return "bytes"
    if isinstance(value, (list, tuple)):
        inner = sorted({value_type(v) for v in value})
        if isinstance(value, tuple) and len(inner) == 1:
            return f"tuple[{inner[0]}, ...]"
        if isinstance(value, tuple):
            return "tuple[" + ", ".join(value_type(v) for v in value) + "]"
        return f"list[{' | '.join(inner) or 'Any'}]"
    if isinstance(value, dict):
        ks = sorted({value_type(k) for k in value})
        vs = sorted({value_type(v) for v in value.values()})
        return f"dict[{' | '.join(ks) or 'Any'}, {' | '.join(vs) or 'Any'}]"
    if value is None:
        return "None"
    return "Any"


def docstring(doc, indent):
    pad = " " * indent
    doc = doc.replace("\\", "\\\\").replace('"""', '\\"\\"\\"')
    lines = doc.splitlines()
    if len(lines) == 1:
        return f'{pad}"""{lines[0]}"""'
    body = "\n".join((pad + line) if line.strip() else "" for line in lines)
    return f'{pad}"""\n{body}\n{pad}"""'


