#!/usr/bin/env python3
"""Generate the type stubs of the native module `fontpixel._native`.

Writes, under crates/fontpixel-py/python/fontpixel/:

* ``types.py`` -- a real (runtime-importable) module with a ``TypedDict`` for
  every serde struct and a ``Literal`` alias for every unit-only serde enum of
  `fontpixel` and `fontpixel-ops`, plus the shared argument aliases
  (``Buffer``, ``StrPath``, ``CodepointLike``, ``Resources``, ...);
* one ``.pyi`` stub per native module: ``_native/__init__.pyi`` (the classes,
  functions, constants and exceptions re-exported by ``fontpixel``),
  ``_native/_ops.pyi``, ``_native/_bdfparser.pyi`` and the public native
  submodules ``formats/`` (one stub per codec namespace), ``sfnt/``, ``woff/``,
  ``outline/``, ``variants.pyi`` and ``merge.pyi``.

The pure-Python modules (``fontpixel.ops``, ``fontpixel.compat.bdfparser``)
carry inline annotations instead.

Sources of truth:

1. The built extension (introspection): every module, class, method,
   property, function and constant, with parameter names, kinds and defaults
   from ``__text_signature__`` and the docstrings. Nothing is listed by hand,
   so a new binding shows up in the stubs automatically.
2. The binding sources (``rust_scan.py``): the Rust parameter/return types of
   every ``#[pyfunction]``/``#[pymethods]`` item and, for ``&Bound<PyAny>``
   parameters, the serde type or ``*_arg`` helper the body converts them with.
3. nightly rustdoc JSON of `fontpixel`/`fontpixel-ops` (``serde_shapes.py``):
   the serde shapes behind every dict/enum string.
4. ``pyi_overrides.py``: types for what the first three cannot see
   (functions generated by ``macro_rules!``, ``PyAny`` results built by hand).

Usage:
    tools/bindings/gen_pyi.py [--rustdoc DIR] [--check] [--report] [--strict]

``DIR`` holds ``fontpixel.json``/``fontpixel_ops.json`` (default
``$FONTPIXEL_RUSTDOC_TARGET/doc``, else ``target/rustdoc-json/doc``; build them
with ``tools/bindings/gate.sh``). Run with the Python that has the extension
installed (``maturin develop``). ``--check`` writes nothing and exits 1 if a
committed file differs or is stale; ``--report`` prints typing coverage;
``--strict`` fails when any parameter or result is left as an unexplained
``Any``.
"""
