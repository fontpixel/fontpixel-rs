TYPES_IMPORTS = {"os", "Callable", "Mapping", "Sequence", "TYPE_CHECKING", "Any", "List", "Literal",
                 "Protocol", "TypedDict", "Union"}


ALLOWLIST = HERE / "stubtest-allowlist.txt"


def build(rustdoc_dir):
    fns, classes = rust_scan.scan(SRC)
    mods = native_modules()
    model, class_home = collect(mods)
    reserved = set(TYPES_IMPORTS)
    class_names = {c.name for m in model.values() for c in m.classes}
    reserved |= set(re.findall(r"^(?:class )?(\w+)(?: = |\()", ovr.PRELUDE, re.M))
    serde = serde_shapes.SerdeModel(rustdoc_dir, reserved, class_names)
    ovr.bind_serde(serde)
    typer = Typer(serde, fns, classes, class_home)
    renderer = Renderer(model, typer, class_home)
    rendered = {}
    for name, m in model.items():
        rendered[PKG / m.path] = renderer.render(m)
    files = {PKG / "types.py": render_types(serde, typer.bytes_views)}
    files.update(rendered)
    files[ALLOWLIST] = render_allowlist(serde, renderer.allow)
    return files, typer, model


def render_allowlist(serde, entries):
    """stubtest allowlist: each entry is generated with the reason it is needed."""
    out = ["# Generated by tools/bindings/gen_pyi.py; do not edit by hand.",
           "# mypy.stubtest allowlist for the fontpixel stubs (tools/bindings/stubtest.py).",
           "#",
           "# Every entry is a false positive or a deliberate omission:",
           ""]
    for reason, names in sorted(entries.items()):
        out.append("# " + reason)
        out += sorted(set(names))
        out.append("")
    lits = sorted(s.name for s in serde.shapes.values() if s.kind == "literal")
    lits += re.findall(r"^(\w+) = Literal\[", ovr.PRELUDE, re.M)
    single = sorted(s.name for s in serde.shapes.values() if s.kind == "union" and len(s.members) == 1)
    out.append("# fontpixel.types: `X = Literal[...]` aliases are real typing objects at runtime;")
    out.append("# stubtest expects a multi-value Literal alias to be a typing.Union at runtime")
    out.append("# (\"is not a Union\") and does not recognise single-value Literal aliases.")
    out += [f"fontpixel.types.{n}" for n in sorted(lits)]
    out.append("")
    out.append("# fontpixel.types: a data-carrying enum with a single variant is an alias of that")
    out.append("# variant's TypedDict class; stubtest does not recognise a class object as an alias.")
    out += [f"fontpixel.types.{n}" for n in single]
    return "\n".join(out).rstrip() + "\n"


def stale_files(files):
    existing = set()
    for p in PKG.rglob("*.pyi"):
        if p.read_text().startswith(HEADER):
            existing.add(p)
    return sorted(existing - set(files))


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--rustdoc", type=Path, default=default_rustdoc())
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--report", action="store_true")
    ap.add_argument("--strict", action="store_true")
    args = ap.parse_args(argv)
    files, typer, model = build(args.rustdoc)
    stale = stale_files(files)
    if args.check:
        bad = [p for p, text in sorted(files.items())
               if not p.exists() or p.read_text() != text]
        for p in bad:
            print(f"out of date: {p.relative_to(ROOT)}", file=sys.stderr)
        for p in stale:
            print(f"stale generated stub: {p.relative_to(ROOT)}", file=sys.stderr)
        if bad or stale:
            print("run tools/bindings/gen_pyi.py to regenerate", file=sys.stderr)
            return 1
    else:
        for path, text in sorted(files.items()):
            path.parent.mkdir(parents=True, exist_ok=True)
            if not path.exists() or path.read_text() != text:
                path.write_text(text)
        for p in stale:
            print(f"stale generated stub (delete it): {p}", file=sys.stderr)
    if args.report or args.strict:
        c = typer.counts
        n_mod = len(model)
        n_cls = sum(len(m.classes) for m in model.values())
        n_fn = sum(len(m.functions) for m in model.values())
        n_mem = sum(len(cl.members) for m in model.values() for cl in m.classes)
        n_const = sum(len(m.constants) for m in model.values())
        print(f"modules {n_mod}, classes {n_cls}, functions {n_fn}, class members {n_mem}, constants {n_const}")
        print(f"parameters {c['params']} ({c['params_any']} untyped), results {c['returns']} "
              f"({c['returns_any']} untyped), properties {c['properties']} ({c['properties_any']} untyped)")
        for u in typer.unresolved:
            print("  untyped:", u)
        if args.strict and typer.unresolved:
            return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
