# ------------------------------------------------------------------ runtime


@dataclass
class Param:
    name: str
    kind: str          # positional_only | positional_or_keyword | keyword_only | var_positional | var_keyword
    has_default: bool
    default: object = None


@dataclass
class Callable_:
    qual: str          # e.g. fontpixel.Font.glyph
    name: str
    kind: str          # function | method | static | classmethod | new | property
    params: list
    doc: str
    obj: object = None
    writable: bool = False
    rust: object = None


@dataclass
class Class_:
    qual: str
    name: str
    obj: type
    bases: list
    doc: str
    members: list = field(default_factory=list)
    exception: bool = False


@dataclass
class Module_:
    name: str           # runtime dotted name
    path: str           # stub path relative to PKG
    obj: types.ModuleType
    doc: str
    classes: list = field(default_factory=list)
    functions: list = field(default_factory=list)
    constants: list = field(default_factory=list)    # (name, value)
    submodules: list = field(default_factory=list)   # (attr name, dotted name)
    reexports: list = field(default_factory=list)    # (name, from module)


def text_params(obj):
    """Parameters of a builtin from its `__text_signature__`."""
    try:
        sig = inspect.signature(obj)
    except (TypeError, ValueError):
        return None
    out = []
    for p in sig.parameters.values():
        out.append(Param(p.name, p.kind.name.lower(), p.default is not inspect.Parameter.empty,
                         None if p.default is inspect.Parameter.empty else p.default))
    return out


# CPython supplies the docstrings of slot wrappers (`__contains__`, ...), and
# their wording changes between versions; the stubs use one text
# (tools/bindings/pyapi.py keeps the same table for the reference).
SLOT_DOCS = {"__contains__": "Return key in self."}


def clean_doc(obj):
    if type(obj).__name__ == "wrapper_descriptor" and getattr(obj, "__name__", None) in SLOT_DOCS:
        return SLOT_DOCS[obj.__name__]
    return inspect.cleandoc(getattr(obj, "__doc__", None) or "")


def native_modules():
    """Every native module object with the stub path it is written to."""
    import fontpixel  # noqa: F401
    import fontpixel._native as native
    mods = {"fontpixel._native": (native, "_native/__init__.pyi")}
    mods["fontpixel._native._ops"] = (native._ops, NATIVE_PRIVATE["fontpixel._native._ops"])
    mods["fontpixel._native._bdfparser"] = (native._bdfparser, NATIVE_PRIVATE["fontpixel._native._bdfparser"])

    def walk(prefix, mod, rel):
        for attr, value in sorted(vars(mod).items()):
            if isinstance(value, types.ModuleType) and not attr.startswith("_"):
                dotted = f"{prefix}.{attr}"
                children = [v for v in vars(value).values() if isinstance(v, types.ModuleType)]
                sub_rel = f"{rel}{attr}/__init__.pyi" if children else f"{rel}{attr}.pyi"
                mods[dotted] = (value, sub_rel)
                if children:
                    walk(dotted, value, f"{rel}{attr}/")
    walk("fontpixel", native, "")
    return mods


def collect(mods):
    """Runtime model of every native module."""
    out = {}
    class_home = {}
    for dotted, (mod, rel) in mods.items():
        m = Module_(dotted, rel, mod, clean_doc(mod))
        for attr, value in sorted(vars(mod).items()):
            if attr == "__version__":
                m.constants.append((attr, value))
                continue
            if attr.startswith("__") or (attr.startswith("_") and dotted == "fontpixel._native"):
                continue
            if isinstance(value, types.ModuleType):
                target = next((d for d, (o, _) in mods.items() if o is value and d != dotted), None)
                if target:
                    m.submodules.append((attr, target))
                continue
            if isinstance(value, type):
                m.classes.append(collect_class(dotted, attr, value))
                class_home.setdefault(id(value), (dotted, attr))
            elif callable(value):
                params = text_params(value)
                m.functions.append(Callable_(f"{dotted}.{attr}", attr, "function", params or [],
                                             clean_doc(value), value))
            else:
                m.constants.append((attr, value))
        out[dotted] = m
    return out, class_home


SLOT_DUNDERS = ["__len__", "__iter__", "__next__", "__getitem__", "__setitem__", "__delitem__",
                "__contains__", "__eq__", "__ne__", "__lt__", "__le__", "__gt__", "__ge__",
                "__hash__", "__int__", "__index__", "__bool__", "__bytes__", "__copy__",
                "__deepcopy__", "__enter__", "__exit__", "__add__", "__or__", "__and__",
                "__xor__", "__invert__", "__sub__", "__mul__", "__matmul__", "__neg__", "__repr__",
                "__str__", "__getattr__", "__call__", "__reversed__", "__radd__", "__rsub__",
                "__rmul__", "__rmatmul__", "__ror__", "__rand__", "__rxor__"]


def collect_class(module, name, cls):
    exc = issubclass(cls, BaseException)
    bases = [b for b in cls.__bases__ if b is not object]
    c = Class_(f"{module}.{name}", name, cls, bases, clean_doc(cls), exception=exc)
    if exc:
        return c
    sig = getattr(cls, "__text_signature__", None)
    if sig is not None:
        params = text_params(cls) or []
        c.members.append(Callable_(f"{c.qual}.__new__", "__new__", "new", params, "", cls))
    for attr, value in sorted(vars(cls).items()):
        if attr.startswith("__") and attr not in SLOT_DUNDERS:
            continue
        if attr in ("__repr__", "__str__"):
            continue
        tname = type(value).__name__
        if tname == "getset_descriptor":
            c.members.append(Callable_(f"{c.qual}.{attr}", attr, "property", [], clean_doc(value), value))
        elif tname == "member_descriptor":
            c.members.append(Callable_(f"{c.qual}.{attr}", attr, "property", [], clean_doc(value), value))
        elif tname in ("method_descriptor", "wrapper_descriptor"):
            params = text_params(value)
            if params is None:
                params = [Param("self", "positional_only", False)] + dunder_params(attr)
            c.members.append(Callable_(f"{c.qual}.{attr}", attr, "method", params, clean_doc(value), value))
        elif tname == "classmethod_descriptor":
            params = text_params(getattr(cls, attr)) or []
            c.members.append(Callable_(f"{c.qual}.{attr}", attr, "classmethod", params, clean_doc(value), value))
        elif isinstance(value, staticmethod) or tname == "builtin_function_or_method":
            fn = getattr(cls, attr)
            params = text_params(fn) or []
            c.members.append(Callable_(f"{c.qual}.{attr}", attr, "static", params, clean_doc(fn), fn))
        elif value is None and attr == "__hash__":
            c.members.append(Callable_(f"{c.qual}.__hash__", "__hash__", "unhashable", [], ""))
        elif attr.startswith("_"):
            continue
        else:
            c.members.append(Callable_(f"{c.qual}.{attr}", attr, "classattr", [], "", value))
    return c


def dunder_params(attr):
    one = {"__getitem__", "__delitem__", "__contains__", "__eq__", "__ne__", "__lt__", "__le__",
           "__gt__", "__ge__", "__deepcopy__", "__add__", "__or__", "__and__", "__xor__", "__sub__",
           "__mul__", "__matmul__", "__getattr__"}
    if attr in one:
        return [Param("other" if attr not in ("__getitem__", "__delitem__", "__deepcopy__", "__getattr__") else
                      {"__getitem__": "key", "__delitem__": "key", "__deepcopy__": "memo", "__getattr__": "name"}[attr],
                      "positional_only", False)]
    if attr == "__setitem__":
        return [Param("key", "positional_only", False), Param("value", "positional_only", False)]
    if attr == "__exit__":
        return [Param(n, "positional_only", False) for n in ("exc_type", "exc", "tb")]
    if attr == "__call__":
        return [Param("args", "var_positional", False), Param("kwargs", "var_keyword", False)]
    return []


# ------------------------------------------------------------------ typing


class Typer:
    """Resolves Python types for parameters and results."""

    def __init__(self, serde, rust_fns, rust_classes, class_home):
        self.serde = serde
        self.rust_classes = {c.rust_name: c for c in rust_classes}
        self.py_of_rust = {}
        for c in rust_classes:
            self.py_of_rust[c.rust_name] = c
        self.class_home = class_home
        # Index Rust fns: methods by (rust class, py name); functions by py name.
        self.methods = {}
        self.functions = {}
        for f in rust_fns:
            if f.cls:
                key = (f.cls, f.py_name, "setter" if f.kind == "setter" else "other")
                self.methods[key] = f
            else:
                self.functions.setdefault(f.py_name, []).append(f)
        self.unresolved = []
        self.counts = {"params": 0, "params_any": 0, "returns": 0, "returns_any": 0,
                       "properties": 0, "properties_any": 0}
        self.namespaces = rust_scan.format_namespaces(SRC)
        self.setters = rust_scan.registry_setters(SRC)
        self.ops = rust_scan.ops_operations(SRC)

    # ---------- matching runtime callables to Rust fns
    def rust_for(self, module_name, cls, member):
        if cls is not None:
            rc = self.rust_class_of(cls)
            if rc is None:
                return None
            if member.kind == "new":
                return self.methods.get((rc.rust_name, "__new__", "other"))
            return self.methods.get((rc.rust_name, member.name, "other"))
        cands = self.functions.get(member.name, [])
        if len(cands) == 1 and norm(cands[0].doc) == norm(member.doc):
            return cands[0]
        for f in cands:
            if norm(f.doc) == norm(member.doc):
                return f
        return None

    def rust_class_of(self, cls):
        for rc in self.rust_classes.values():
            mod = rc.module or "builtins"
            if rc.py_name == cls.name and (cls.obj.__module__ == mod):
                return rc
        return None

    def setter_for(self, cls, name):
        rc = self.rust_class_of(cls)
        if rc is None:
            return None
        return self.methods.get((rc.rust_name, name, "setter"))

    # ---------- Rust type text -> Python
    def rust_type(self, text, position, cls_name, hint=None):
        """Python type of a Rust type; `position` is "param" or "return"."""
        t = parse_rust_type(text)
        return self.py(t, position, cls_name, hint)

    def py(self, t, pos, cls_name, hint=None):
        full, args = t
        name = full.split("::")[-1]
        if name == "&":
            return self.py(args[0], pos, cls_name, hint)
        if name == "()":
            return "None"
        if name == "tuple":
            return "tuple[" + ", ".join(self.py(a, pos, cls_name) for a in args) + "]"
        if name in ("[]", "[;]"):
            inner = args[0]
            if inner == ("u8", []):
                return "bytes" if pos == "return" else "_t.Buffer"
            return (f"list[{self.py(inner, pos, cls_name)}]" if pos == "return"
                    else f"_c.Sequence[{self.py(inner, pos, cls_name)}]")
        if name in ("PyResult", "Result") and args:
            return self.py(args[0], pos, cls_name, hint)
        if name == "Option" and args:
            return union(self.py(args[0], pos, cls_name, hint), "None")
        if name in ("Vec", "VecDeque", "Box<[]>") and args:
            if args[0] == ("u8", []):
                return "bytes" if pos == "return" else "_t.Buffer | _c.Sequence[int]"
            return (f"list[{self.py(args[0], pos, cls_name)}]" if pos == "return"
                    else f"_c.Sequence[{self.py(args[0], pos, cls_name)}]")
        if name in ("BTreeSet", "HashSet") and args:
            return (f"set[{self.py(args[0], pos, cls_name)}]" if pos == "return"
                    else f"_c.Set[{self.py(args[0], pos, cls_name)}] | frozenset[{self.py(args[0], pos, cls_name)}]")
        if name in ("BTreeMap", "HashMap", "IndexMap") and len(args) == 2:
            k, v = self.py(args[0], pos, cls_name), self.py(args[1], pos, cls_name)
            return f"dict[{k}, {v}]" if pos == "return" else f"_c.Mapping[{k}, {v}]"
        if name in ("Box", "Arc", "Rc", "Cow") and args:
            return self.py(args[0], pos, cls_name, hint)
        if name in serde_shapes.INT:
            return "int"
        if name in ("f32", "f64"):
            return "float"
        if name == "bool":
            return "bool"
        if name in ("str", "String", "char", "PyBackedStr"):
            if hint is not None and pos == "param":
                h = self.pyany(pos, hint)
                if h not in ("Any", "str"):
                    return h
            return "str"
        if name in ("PathBuf", "Path"):
            return "_t.StrPath"
        if name == "PyBackedBytes":
            return "bytes"
        if name in ("Bound", "Borrowed", "Py", "PyRef", "PyRefMut", "Any", "Opt"):
            if name == "Opt":
                return union(self.pyany(pos, hint), "None")
            if name == "Any" and not args:
                return self.pyany(pos, hint)
            inner = args[-1] if args else ("PyAny", [])
            return self.py_object(inner[0], pos, cls_name, hint)
        if name == "PyObject":
            return self.pyany(pos, hint)
        if name == "Self":
            return cls_name or "Any"
        if self.binding_class(name):
            return self.class_ref(self.py_of_rust[name])
        if name in ovr.RUST_TYPES:
            return ovr.RUST_TYPES[name]
        shape = self.serde_name(full)
        if shape:
            return shape
        return "Any"

    def py_object(self, name, pos, cls_name, hint):
        table = {"PyAny": None, "PyDict": "dict[str, Any]", "PyList": "list[Any]",
                 "PyTuple": "tuple[Any, ...]", "PyBytes": "bytes", "PyString": "str",
                 "PyType": "type", "PyModule": "_types.ModuleType", "PyIterator": "_c.Iterator[Any]",
                 "PyInt": "int", "PyFloat": "float", "PyBool": "bool", "PyByteArray": "bytearray",
                 "PySequence": "_c.Sequence[Any]", "PyMapping": "_c.Mapping[str, Any]",
                 "PySet": "set[Any]", "PyFrozenSet": "frozenset[Any]", "PyBaseException": "BaseException"}
        if name in table and table[name] is not None:
            return table[name]
        if name == "PyAny":
            return self.pyany(pos, hint)
        if name == "Self":
            return cls_name or "Any"
        if self.binding_class(name):
            return self.class_ref(self.py_of_rust[name])
        return "Any"

    def binding_class(self, name):
        """Whether `name` (as written in the current file) is a binding
        `#[pyclass]` struct rather than a core type of the same name."""
        rc = self.py_of_rust.get(name)
        if rc is None:
            return False
        if name.startswith("Py") or rc.file == self.cur_file or self.cur_file is None:
            return True
        return rust_scan.USES.get(self.cur_file, {}).get(name, "").startswith("crate::")

    def pyany(self, pos, hint):
        if hint is None:
            return "Any"
        kind, value, file = hint
        if kind == "helper":
            return self.helper_type(value, file)
        with self.in_file(file):
            shape = self.rust_type(value, "param", None)
            shape = None if shape == "Any" else shape
        return shape or "Any"

    cur_file = None

    def in_file(self, file):
        """Resolve Rust paths with `file`'s `use` declarations."""
        typer = self

        class _Ctx:
            def __enter__(self):
                self.prev = typer.cur_file
                typer.cur_file = file

            def __exit__(self, *exc):
                typer.cur_file = self.prev
        return _Ctx()

    def helper_type(self, name, file):
        """Python type a conversion helper accepts: an explicit HELPERS entry,
        else the serde shape or class its Rust result is (same file first)."""
        for key in (f"{file}:{name}", name):
            if key in ovr.HELPERS:
                return ovr.HELPERS[key]
        rets = rust_scan.HELPER_RETURNS
        ret = rets.get(file, {}).get(name)
        home = file
        if ret is None:
            found = [(f, r[name]) for f, r in rets.items() if name in r]
            home, ret = found[0] if len(found) == 1 else (None, None)
        if ret is None:
            return "Any"
        with self.in_file(home):
            t = self.rust_type(ret, "return", None)
        return t if t not in ("None",) else "Any"

    def full_path(self, rust_text):
        """Expand a path as written in the current binding file to a crate path."""
        text = re.sub(r"<.*>", "", rust_text).strip().lstrip("&").strip()
        segs = text.split("::")
        uses = rust_scan.USES.get(self.cur_file, {})
        if segs[0] == "f":
            segs = ["fontpixel", "formats"] + segs[1:]
        elif segs[0] in uses:
            segs = uses[segs[0]].split("::") + segs[1:]
        elif segs[0] == "crate":
            return None
        if segs[0] not in ("fontpixel", "fontpixel_ops"):
            return None
        return "::".join(segs)

    def serde_name(self, rust_text):
        """`fontpixel.types` name of a Rust serde type written as in the source."""
        full = self.full_path(rust_text)
        if full:
            canon = self.serde.canonical(full) or full
            if canon in self.serde.names:
                return "_t." + self.serde.names[canon]
        text = re.sub(r"<.*>", "", rust_text).strip().lstrip("&")
        text = text.replace("crate::", "").replace("fontpixel::", "")
        text = re.sub(r"^f::", "formats::", text)
        if text in ovr.RUST_TYPES:
            return ovr.RUST_TYPES[text]
        segs = text.split("::")
        hits = [p for p in self.serde.shapes if p.split("::")[-len(segs):] == segs]
        if len(hits) > 1:
            pref = [p for p in hits if p.startswith("fontpixel::") and not p.startswith("fontpixel_ops")]
            exact = [p for p in hits if p.split("::")[1:] == segs]
            hits = exact or pref if len(exact or pref) == 1 else hits
        if len(hits) == 1:
            return "_t." + self.serde.names[hits[0]]
        return None

    def ret_hint_type(self, hint):
        """Python type of a `PyAny` result from its body hint."""
        if hint is None:
            return None
        if hint[0] == "bytes":
            return "bytes"
        kind, text, file = hint
        with self.in_file(file):
            if kind == "type":
                t = self.rust_type(text, "return", None)
                return None if "Any" in split_union(t) else t
            full = self.full_path(text)
        if not full:
            return None
        out = self.serde.fn_output(full)
        if out is None or out == "Any":
            return None
        return qualify_serde(out, self.serde)

    bytes_views: dict = {}

    def bytes_view(self, name, fields):
        """`fontpixel.types` name of serde shape `name` with `fields` as `bytes`
        (results the bindings build with `with_bytes`)."""
        view = name + "Bytes"
        if view in self.serde.names.values():
            raise SystemExit(f"bytes view {view} clashes with a serde type name")
        self.bytes_views[view] = (name, tuple(fields))
        return "_t." + view

    def class_ref(self, rc):
        return f"@{rc.module or 'fontpixel'}.{rc.py_name}"

    # ---------- functions generated by macro_rules!
    def macro_sig(self, f):
        """Types of a callable generated by a `macro_rules!` template, from the
        invocation tables (formats_direct.rs `namespaces!`, formats_options.rs
        `setters!`)."""
        if f.qual in self._macro_cache:
            return self._macro_cache[f.qual]
        sig = self._macro_sig(f)
        self._macro_cache[f.qual] = sig
        return sig

    _macro_cache: dict = {}

    def _macro_sig(self, f):
        m = re.fullmatch(r"fontpixel\._native\._ops\.(\w+)", f.qual)
        if m and m.group(1) in self.ops:
            with self.in_file("ops.rs"):
                request = self.serde_name(self.ops[m.group(1)]) or "Any"
            return {"request": request, "files": "_t.Files", "options": "Any",
                    "return": "@fontpixel.ops.OperationResult"}
        m = re.fullmatch(r"fontpixel\._native\.Registry\.set_\w+_options", f.qual)
        if m:
            t = re.search(r"apply a `([^`]+)` dict", f.doc)
            shape = self.serde_name(t.group(1)) if t else None
            return {"options": shape, "return": "None"} if shape else None
        m = re.fullmatch(r"fontpixel\.formats\.(\w+)\.(detect|read|write)", f.qual)
        if not m or m.group(1) not in self.namespaces:
            return None
        ns = self.namespaces[m.group(1)]
        kind, args = ns[m.group(2)]
        limits = "_t.ResourceLimits"
        if m.group(2) == "detect":
            return {"data": "_t.Buffer | _c.Sequence[int]", "name": "str", "limits": limits,
                    "return": "_t.Confidence"}
        if m.group(2) == "read":
            sig = {"data": "_t.ReadInput", "name": "str", "resources": "_t.Resources",
                   "limits": limits, "directory": "str"}
            if kind in ("bytes_limits", "bytes_opts_limits", "bytes_opts"):
                sig["data"] = "_t.Buffer | _c.Sequence[int]"
            if kind == "registry":
                opts = self.setters["read"].get(args[0].strip('"'))
                model = "FontSet"
            else:
                opts = args[1] if len(args) > 1 else None
                model = self.serde.read_model(args[0]) or "FontSet"
            if opts:
                sig["options"] = self.serde_name(opts) or "Any"
            sig["return"] = f"tuple[@fontpixel.{model}, _t.Report]"
            return sig
        sig = {"fonts": "@fontpixel.FontSet | @fontpixel.Font", "primary_name": "str",
               "strict": "bool", "transport_limits": "_t.TransportLimits", "return": "@fontpixel.Written"}
        if kind == "registry":
            opts = self.setters["write"].get(args[0].strip('"'))
        else:
            opts = args[-1]
        if opts:
            sig["options"] = self.serde_name(opts) or "Any"
        if kind == "x_opts":
            sig["return"] = "tuple[bytes, _t.Report]"
        return sig


ALLOWED_ANY = ("_c.Mapping[str, Any]", "dict[str, Any]", "_c.Callable[..., Any]", "list[Any]")


def has_any(t):
    """Whether `t` contains an unexplained `Any`."""
    if t is None:
        return True
    for ok in ALLOWED_ANY[:3]:
        t = t.replace(ok, "")
    return re.search(r"(?<![\w.])Any(?![\w])", t) is not None


def norm(doc):
    return " ".join((doc or "").split())


def union(a, b):
    """`a | b` without repeating members."""
    if a == "Any":
        return a
    parts = split_union(a)
    parts += [x for x in split_union(b) if x not in parts]
    return " | ".join(parts)


def split_union(t):
    out, depth, cur = [], 0, ""
    for ch in t:
        if ch == "[":
            depth += 1
        elif ch == "]":
            depth -= 1
        if ch == "|" and depth == 0:
            out.append(cur.strip())
            cur = ""
            continue
        cur += ch
    out.append(cur.strip())
    return out


def parse_rust_type(text):
    """Parse a Rust type into (name, [args]) trees; lifetimes are dropped."""
    toks = re.findall(r"::|->|'\w+|[A-Za-z_][\w]*|\d+|[<>(),\[\];&*]", text)
    pos = 0

    def peek():
        return toks[pos] if pos < len(toks) else None

    def take():
        nonlocal pos
        pos += 1
        return toks[pos - 1]

    def ty():
        nonlocal pos
        while peek() in ("dyn", "impl", "mut", "const"):
            take()
        tok = peek()
        if tok == "&":
            take()
            if peek() and peek().startswith("'"):
                take()
            if peek() == "mut":
                take()
            return ("&", [ty()])
        if tok == "(":
            take()
            items = []
            while peek() != ")":
                items.append(ty())
                if peek() == ",":
                    take()
            take()
            return ("()", []) if not items else ("tuple", items) if len(items) > 1 else items[0]
        if tok == "[":
            take()
            inner = ty()
            if peek() == ";":
                take()
                take()
                take()
                return ("[;]", [inner])
            take()
            return ("[]", [inner])
        name = take()
        while peek() == "::":
            take()
            name = name + "::" + take()
        args = []
        if peek() == "<":
            take()
            while peek() != ">":
                if peek() and peek().startswith("'"):
                    take()
                else:
                    args.append(ty())
                if peek() == ",":
                    take()
            take()
        return (name, args)

    return ty()


