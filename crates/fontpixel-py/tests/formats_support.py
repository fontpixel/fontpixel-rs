"""Shared round-trip cases for the format binding tests.

Every catalogue format ID has one case: a source font, the typed write options
(and the equivalent frozen-CLI flags), and the typed read options needed to
read the output back (and their CLI flags). `data/formats/cli_golden.json`
holds the SHA-256 of every asset the frozen CLI wrote for the case and of the
YAFF the CLI produced when reading that output back; it is regenerated by
`data/formats/regen_cli_golden.py`. The tests repeat each operation through
the Python bindings and compare with those hashes.
"""
