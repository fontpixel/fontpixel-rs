def case(fid):
    """The case of `fid` (default: the Unicode 3x5 font, no options)."""
    c = CASES.get(fid, Case("uni3"))
    if c.read.get("layout") == RAW_LAYOUT:
        import fontpixel.formats.raw

        c = Case(**{**c.__dict__, "read": {"layout": fontpixel.formats.raw.raw_layout(3, 6)}})
    return c


def source_bytes(fid):
    c = case(fid)
    if c.source == "native":
        return NATIVE[fid]()
    with open(SOURCES[c.source], "rb") as f:
        return f.read()


def primary_name(status):
    exts = status["format"]["extensions"]
    return f"font.{exts[0]}" if exts else "font"


def assets_of(written):
    """`{path: bytes}` of a `Written` or `OutputBundle`."""
    bundle = getattr(written, "output", written)
    return {a.path: a.data for a in bundle.assets}


def single(written):
    """The only asset's bytes of a `Written`."""
    return written.output.into_single()


def sha(data):
    return hashlib.sha256(data).hexdigest()


def load_golden():
    with open(GOLDEN) as f:
        return json.load(f)
