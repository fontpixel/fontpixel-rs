# Byte-authored native fixtures, ported from crates/fontpixel/tests/<format>.rs.
def _daisy():
    b = bytearray(b"3\x9b")
    for cp in range(33, 125):
        if cp in (96, 123):
            continue
        b.append(66)
        g = [0] * 8
        if cp == 65:
            g[0], g[1], g[6] = 0x80, 0x40, 0x20
        b += bytes(g)
    b += bytes([31, 30, 2])
    return bytes(b)


def _tasprint():
    b = bytearray(1920)
    p = 33 * 20
    b[p], b[p + 1], b[p + 12] = 0x80, 0x40, 0x20
    return bytes(b)


def _hrcg():
    return bytes(
        0x80 if i % 8 == 0 else ((1 << (i % 7)) | (128 if i % 2 == 0 else 0)) for i in range(768)
    )


def _hmzk():
    b = bytearray(84)
    b[:4] = b"HMZK"
    b[4:14] = b"\xff" * 10
    b[4] = 1
    b[14] = 4
    b[16] = 65
    b[18] = 66
    for i in range(64):
        b[20 + i] = (i * 37) & 0xFF
    return bytes(b)


def _fbit():
    b = bytearray(44)
    b[2:6] = b"fbit"
    b[6:8] = (128).to_bytes(2, "big")
    b[24:26] = (3).to_bytes(2, "big")
    b[26:28] = (3).to_bytes(2, "big")
    b[32:34] = (0x817E).to_bytes(2, "big")
    b[34:36] = (0x8180).to_bytes(2, "big")
    b[36:38] = (1).to_bytes(2, "big")
    b[38:40] = (62).to_bytes(2, "big")
    b[40:42] = (63).to_bytes(2, "big")
    b[42:44] = (2).to_bytes(2, "big")
    b += bytes([0xAF, 0x80, 0x72, 0])
    return bytes(b)


def _hanfont():
    out = bytearray(360 * 32)
    for slot in range(360):
        for p in range(32):
            out[slot * 32 + p] = ((slot * 29 + p * 47) ^ (slot >> 3)) & 0xFF
    return bytes(out)


NATIVE = {
    "daisy": _daisy,
    "tasprint": _tasprint,
    "hrcg": _hrcg,
    "hmzk": _hmzk,
    "fbit": _fbit,
    "hanfont": _hanfont,
}

# `raw` with the 3x6 cells of the 3x5-block font: RawLayout::new(3, 6), the
# layout the CLI builds from `--raw-width 3 --raw-height 6`.
RAW_LAYOUT = "raw_layout(3, 6)"


@dataclass
class Case:
    """One format's round-trip configuration."""

    source: str
    write: dict = field(default_factory=dict)
    cli: list = field(default_factory=list)
    read: dict = field(default_factory=dict)
    cli_read: list = field(default_factory=list)
    # Native sources need an explicit input format, read options and CLI flags.
    source_read: dict = field(default_factory=dict)
    cli_source_read: list = field(default_factory=list)


