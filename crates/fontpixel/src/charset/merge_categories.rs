/// Pinned Unicode version.
pub const UNICODE_VERSION: &str = "17.0.0";
/// Inclusive Unicode block/category range.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct UnicodeRange {
    /// First code point.
    pub start: u32,
    /// Last code point.
    pub end: u32,
    /// Name.
    pub name: &'static str,
}
/// Exact East Asian Width property.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum EastAsianWidth {
    /// Ambiguous.
    Ambiguous,
    /// Fullwidth.
    Fullwidth,
    /// Halfwidth.
    Halfwidth,
    /// Neutral.
    Neutral,
    /// Narrow.
    Narrow,
    /// Wide.
    Wide,
}
/// Whether a numeric code is a Unicode scalar.
pub const fn is_scalar(cp: u32) -> bool {
    cp <= 0x10ffff && !(cp >= 0xd800 && cp <= 0xdfff)
}
fn contains(ranges: &[UnicodeRange], cp: u32) -> bool {
    let index = ranges.partition_point(|r| r.end < cp);
    ranges.get(index).is_some_and(|r| r.start <= cp)
}
/// Explicit CJK block policy.
pub fn is_cjk(cp: u32) -> bool {
    is_scalar(cp) && contains(CJK_RANGES, cp)
}
/// Scalar complement of CJK, including geometric symbols.
pub fn is_western(cp: u32) -> bool {
    is_scalar(cp) && !is_cjk(cp)
}
/// Box/block/braille and the specified Powerline PUA interval.
pub fn is_geometric(cp: u32) -> bool {
    contains(GEOMETRIC_RANGES, cp)
}
/// Han ideograph blocks for modal width.
pub fn is_han(cp: u32) -> bool {
    contains(HAN_RANGES, cp)
}
/// Unicode block, or None for No_Block or invalid scalar.
pub fn unicode_block(cp: u32) -> Option<&'static UnicodeRange> {
    if !is_scalar(cp) {
        return None;
    }
    let index = UNICODE_BLOCKS.partition_point(|r| r.end < cp);
    UNICODE_BLOCKS.get(index).filter(|r| r.start <= cp)
}
/// Exact EAW; unspecified scalars Neutral, invalid scalars None.
pub fn east_asian_width(cp: u32) -> Option<EastAsianWidth> {
    if !is_scalar(cp) {
        return None;
    }
    let index = EAST_ASIAN_WIDTH.partition_point(|r| r.1 < cp);
    Some(
        EAST_ASIAN_WIDTH
            .get(index)
            .filter(|r| r.0 <= cp)
            .map_or(EastAsianWidth::Neutral, |r| r.2),
    )
}

