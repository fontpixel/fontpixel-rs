/// Amiga output packaging.
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq)]
#[cfg_attr(feature = "serde", derive(serde::Serialize, serde::Deserialize))]
#[cfg_attr(feature = "serde", serde(rename_all = "snake_case"))]
pub enum Packaging {
    /// `.font` primary names or multiple strikes produce contents plus sidecars.
    #[default]
    Auto,
    /// Always produce a contents file and strike sidecars.
    Contents,
    /// Produce one direct hunk strike.
    Strike,
}
/// Amiga input options.
#[derive(Debug, Clone, Default)]
#[cfg_attr(feature = "serde", derive(serde::Serialize, serde::Deserialize))]
#[cfg_attr(feature = "serde", serde(deny_unknown_fields, default))]
pub struct AmigaReadOptions {}
/// Amiga output choices.
#[derive(Debug, Clone)]
#[cfg_attr(feature = "serde", derive(serde::Serialize, serde::Deserialize))]
#[cfg_attr(feature = "serde", serde(deny_unknown_fields, default))]
pub struct AmigaWriteOptions {
    /// Contents bundle or direct hunk.
    pub packaging: Packaging,
    /// Explicitly encode Unicode U+0000 through U+00FF as ISO-8859-1 codes.
    pub unicode_as_latin1: bool,
    /// Threshold for new grayscale input; existing color planes are preserved by default.
    pub gray_threshold: Option<u8>,
    /// Emit this many indexed color planes (1–8); source color depth is preserved by default.
    pub color_depth: Option<u8>,
    /// Aggregate resource and glyph budgets, shared across every strike.
    pub limits: ResourceLimits,
    /// Maximum cumulative generated bytes.
    pub max_output_bytes: usize,
}
impl Default for AmigaWriteOptions {
    fn default() -> Self {
        Self {
            packaging: Packaging::Auto,
            unicode_as_latin1: true,
            gray_threshold: None,
            color_depth: None,
            limits: ResourceLimits::default(),
            max_output_bytes: 64 * 1024 * 1024,
        }
    }
}
/// Amiga registry codec.
#[derive(Debug, Clone, Default)]
#[cfg_attr(feature = "serde", derive(serde::Serialize, serde::Deserialize))]
#[cfg_attr(feature = "serde", serde(deny_unknown_fields, default))]
pub struct AmigaCodec {
    /// Input interpretation.
    pub read_options: AmigaReadOptions,
    /// Output representation.
    pub write_options: AmigaWriteOptions,
}
impl FormatDetector for AmigaCodec {
    fn detect(&self, c: &mut ReadContext<'_>) -> Result<Confidence> {
        let b = c.bytes();
        if b.starts_with(&[0, 0, 3, 0xf3]) {
            let mut budget = Budget::new(c.retained_input_bytes(), c.limits())?;
            return Ok(
                if hunks(b, c.limits(), &mut budget)
                    .ok()
                    .and_then(|h| {
                        h.segments
                            .first()
                            .map(|s| matches!(u16_at(s, 18, BE), Ok(0xf80)))
                    })
                    .unwrap_or(false)
                {
                    Confidence::Certain
                } else {
                    Confidence::NoMatch
                },
            );
        }
        Ok(
            if matches!(u16_at(b, 0, BE), Ok(0xf00 | 0xf02))
                && u16_at(b, 2, BE).is_ok_and(|count| b.len() >= 4 + usize::from(count) * 260)
            {
                Confidence::Certain
            } else {
                Confidence::NoMatch
            },
        )
    }
}
impl FormatReader<FontSet> for AmigaCodec {
    fn read(&self, c: &mut ReadContext<'_>, _: &ReadOptions) -> Result<(FontSet, Report)> {
        read(c, &self.read_options)
    }
}
impl FormatWriter<FontSet> for AmigaCodec {
    fn write(&self, s: &FontSet, o: &WriteOptions) -> Result<Written> {
        write(s, o, &self.write_options)
    }
}
struct Hunks<'a> {
    segments: Vec<std::borrow::Cow<'a, [u8]>>,
    relocs: BTreeMap<(usize, usize), usize>,
}
impl<'a> Hunks<'a> {
    fn pointer(&self, source: usize, at: usize, n: usize) -> Result<&[u8]> {
        let segment = self
            .segments
            .get(source)
            .ok_or_else(|| invalid("invalid Amiga segment"))?;
        let offset = u32_at(segment, at, BE)? as usize;
        let target = *self.relocs.get(&(source, at)).unwrap_or(&source);
        slice(
            self.segments
                .get(target)
                .ok_or_else(|| invalid("invalid Amiga relocation target"))?,
            offset,
            n,
        )
    }
}
fn hunks<'a>(b: &'a [u8], l: &ResourceLimits, budget: &mut Budget) -> Result<Hunks<'a>> {
    if u32_at(b, 0, BE)? != 0x3f3 || u32_at(b, 4, BE)? != 0 {
        return Err(invalid(
            "Amiga font requires HUNK_HEADER without resident libraries",
        ));
    }
    let table = u32_at(b, 8, BE)? as usize;
    let first = u32_at(b, 12, BE)? as usize;
    let last = u32_at(b, 16, BE)? as usize;
    if last < first || first != 0 || last >= table {
        return Err(invalid("invalid Amiga hunk range"));
    }
    let count = last - first + 1;
    check(count, l.max_resources, "Amiga hunks")?;
    check(count * 4, l.max_table_bytes, "Amiga hunk table")?;
    slice(b, 20, count * 4)?;
    budget.items::<std::borrow::Cow<'_, [u8]>>(count)?;
    let mut out = Hunks {
        segments: Vec::with_capacity(count),
        relocs: BTreeMap::new(),
    };
    let mut at = 20 + count * 4;
    let mut active = None;
    while at < b.len() {
        let kind = u32_at(b, at, BE)? & 0x3fffffff;
        at += 4;
        match kind {
            0x3e9 | 0x3ea => {
                if active.is_some() || out.segments.len() >= count {
                    return Err(invalid("unexpected Amiga data hunk"));
                }
                let words = u32_at(b, at, BE)? as usize;
                at += 4;
                let n = words
                    .checked_mul(4)
                    .ok_or_else(|| invalid("Amiga hunk length overflow"))?;
                check(n, l.max_table_bytes, "Amiga hunk bytes")?;
                let allocation =
                    (u32_at(b, 20 + out.segments.len() * 4, BE)? & 0x3fffffff) as usize;
                if words > allocation {
                    return Err(invalid("Amiga hunk exceeds declared allocation"));
                }
                let data = slice(b, at, n)?;
                active = Some(out.segments.len());
                out.segments.push(std::borrow::Cow::Borrowed(data));
                at += n;
            }
            0x3eb => {
                if active.is_some() || out.segments.len() >= count {
                    return Err(invalid("unexpected Amiga BSS hunk"));
                }
                let words = u32_at(b, at, BE)? as usize;
                at += 4;
                let n = words
                    .checked_mul(4)
                    .ok_or_else(|| invalid("Amiga BSS overflow"))?;
                check(n, l.max_table_bytes, "Amiga BSS bytes")?;
                if words > (u32_at(b, 20 + out.segments.len() * 4, BE)? & 0x3fffffff) as usize {
                    return Err(invalid("Amiga BSS exceeds allocation"));
                }
                budget.add(n)?;
                active = Some(out.segments.len());
                out.segments.push(std::borrow::Cow::Owned(vec![0; n]));
            }
            0x3fc | 0x3f7 => {
                let source =
                    active.ok_or_else(|| invalid("Amiga short relocation without segment"))?;
                loop {
                    let n = u16_at(b, at, BE)? as usize;
                    at += 2;
                    if n == 0 {
                        break;
                    }
                    let target = u16_at(b, at, BE)? as usize;
                    at += 2;
                    if target >= count {
                        return Err(invalid("Amiga relocation target out of range"));
                    }
                    slice(b, at, n * 2)?;
                    budget.add(n.saturating_mul(64))?;
                    for i in 0..n {
                        let off = usize::from(u16_at(b, at + i * 2, BE)?);
                        if !off.is_multiple_of(2) {
                            return Err(invalid("unaligned Amiga relocation"));
                        }
                        slice(&out.segments[source], off, 4)?;
                        if out.relocs.insert((source, off), target).is_some() {
                            return Err(invalid("duplicate Amiga relocation"));
                        }
                    }
                    at += n * 2;
                }
                if !at.is_multiple_of(4) {
                    slice(b, at, 2)?;
                    at += 2;
                }
            }
            0x3e8 => {
                let n = (u32_at(b, at, BE)? as usize)
                    .checked_mul(4)
                    .ok_or_else(|| invalid("Amiga hunk name overflow"))?;
                at += 4;
                slice(b, at, n)?;
                at += n;
            }
            0x3ec => {
                let source = active.ok_or_else(|| invalid("Amiga relocation without segment"))?;
                loop {
                    let n = u32_at(b, at, BE)? as usize;
                    at += 4;
                    if n == 0 {
                        break;
                    }
                    let target = u32_at(b, at, BE)? as usize;
                    at += 4;
                    if target >= count {
                        return Err(invalid("Amiga relocation target out of range"));
                    }
                    check(
                        n.checked_mul(4)
                            .ok_or_else(|| invalid("Amiga relocation overflow"))?,
                        l.max_table_bytes,
                        "Amiga relocation table",
                    )?;
                    slice(b, at, n * 4)?;
                    budget.add(n.saturating_mul(64))?;
                    for i in 0..n {
                        let off = u32_at(b, at + i * 4, BE)? as usize;
                        if !off.is_multiple_of(2) {
                            return Err(invalid("unaligned Amiga relocation"));
                        }
                        slice(&out.segments[source], off, 4)?;
                        if out.relocs.insert((source, off), target).is_some() {
                            return Err(invalid("duplicate Amiga relocation"));
                        }
                    }
                    at += n * 4;
                }
            }
            0x3f1 => {
                let n = (u32_at(b, at, BE)? as usize)
                    .checked_mul(4)
                    .ok_or_else(|| invalid("Amiga debug length overflow"))?;
                at += 4;
                slice(b, at, n)?;
                at += n;
            }
            0x3f0 => loop {
                let n = (u32_at(b, at, BE)? as usize)
                    .checked_mul(4)
                    .ok_or_else(|| invalid("Amiga symbol length overflow"))?;
                at += 4;
                if n == 0 {
                    break;
                }
                slice(b, at, n + 4)?;
                at += n + 4;
            },
            0x3f2 => {
                if active.take().is_none() {
                    return Err(invalid("unexpected Amiga HUNK_END"));
                }
            }
            _ => return Err(invalid(format!("unsupported Amiga hunk type 0x{kind:x}"))),
        }
    }
    if active.is_some() || out.segments.len() != count {
        return Err(invalid("incomplete Amiga hunk container"));
    }
    Ok(out)
}
/// Decode a direct strike or all caller-resolved contents resources.
pub fn read(c: &mut ReadContext<'_>, _: &AmigaReadOptions) -> Result<(FontSet, Report)> {
    let mut budget = Budget::new(c.retained_input_bytes(), c.limits())?;
    let mut report = Report::default();
    let mut set = FontSet::default();
    if c.bytes().starts_with(&[0, 0, 3, 0xf3]) {
        set.fonts.push(parse_strike(
            c.bytes(),
            c.limits(),
            &mut budget,
            &mut report,
            0,
        )?);
    } else {
        let b = c.bytes();
        let magic = u16_at(b, 0, BE)?;
        if magic != 0xf00 && magic != 0xf02 {
            return Err(invalid("not an Amiga bitmap contents file"));
        }
        let count = u16_at(b, 2, BE)? as usize;
        check(count, c.limits().max_resources, "Amiga strike count")?;
        check(count * 260, c.limits().max_table_bytes, "Amiga contents")?;
        let records = slice(b, 4, count * 260)?;
        budget.add(records.len())?;
        budget.items::<Font>(count)?;
        let records = records.to_vec();
        let mut total_glyphs = 0usize;
        for i in 0..count {
            let entry = &records[i * 260..(i + 1) * 260];
            let tag_count = if magic == 0xf02 {
                u16_at(entry, 254, BE)? as usize
            } else {
                0
            };
            if tag_count > 32 {
                return Err(invalid("Amiga tag count exceeds filename field"));
            }
            let name_limit = if tag_count == 0 {
                if magic == 0xf02 { 254 } else { 256 }
            } else {
                256 - tag_count * 8
            };
            let name = &entry[..name_limit];
            let end = name
                .iter()
                .position(|x| *x == 0)
                .ok_or_else(|| invalid("Amiga resource name lacks terminator"))?;
            budget.add(end * 2 + 64)?;
            let path = ResourcePath::new(latin(&name[..end]))?;
            let data = c.resource_limited(&path, budget.max.saturating_sub(budget.used))?;
            budget.add(data.len())?;
            let mut remaining = c.limits().clone();
            remaining.max_glyphs = remaining.max_glyphs.saturating_sub(total_glyphs);
            let mut font = parse_strike(&data, &remaining, &mut budget, &mut report, i)?;
            total_glyphs = total_glyphs
                .checked_add(font.len())
                .ok_or_else(|| invalid("Amiga glyph count overflow"))?;
            check(total_glyphs, c.limits().max_glyphs, "Amiga total glyphs")?;
            if tag_count > 0 {
                let tags = &entry[256 - tag_count * 8..248];
                budget.add(tags.len() * 2 + 128)?;
                font.headers.push(Property::new(
                    "amiga.contents_tags",
                    PropertyValue::Bytes(tags.to_vec()),
                ));
                for tag in tags.as_chunks::<8>().0 {
                    if u32_at(tag, 0, BE)? == 0x80000001 {
                        font.metrics.resolution = Some(Vector::new(
                            i64::from(u16_at(tag, 4, BE)?),
                            i64::from(u16_at(tag, 6, BE)?),
                        ));
                    }
                }
            }
            if font.metrics.pixel_size != Some(u32::from(u16_at(entry, 256, BE)?)) {
                budget.diagnostic(
                    &mut report,
                    "amiga",
                    "read.contents_size",
                    crate::report::Impact::Repair,
                    Some(i),
                    None,
                    "Contents size differs from authoritative strike",
                )?;
            }
            set.fonts.push(font);
        }
    }
    set.source_format = Some("amiga".into());
    Ok((set, report))
}
fn parse_strike(
    b: &[u8],
    l: &ResourceLimits,
    budget: &mut Budget,
    report: &mut Report,
    fi: usize,
) -> Result<Font> {
    let h = hunks(b, l, budget)?;
    let data = h
        .segments
        .first()
        .ok_or_else(|| invalid("empty Amiga hunk"))?;
    slice(data, 0, 110)?;
    if u16_at(data, 18, BE)? != 0xf80 {
        return Err(invalid("missing Amiga DiskFontHeader"));
    }
    let height = u32::from(u16_at(data, 78, BE)?);
    let style = data[80];
    let flags = data[81];
    let color = style & 64 != 0;
    let first = data[90];
    let last = data[91];
    if last < first || height == 0 {
        return Err(invalid("invalid Amiga character range or height"));
    }
    let count = usize::from(last - first) + 2;
    check(count, l.max_glyphs, "Amiga glyphs")?;
    budget.items::<Glyph>(count)?;
    let stride = u16_at(data, 96, BE)? as usize;
    if !stride.is_multiple_of(2) {
        return Err(invalid("Amiga bitmap rows must be word aligned"));
    }
    let bitmap_size = stride * height as usize;
    check(bitmap_size, l.max_table_bytes, "Amiga bitmap strip")?;
    let depth = if color {
        slice(data, 110, 12)?;
        data[112]
    } else {
        1
    };
    if depth == 0 || depth > 8 {
        return Err(invalid("Amiga color depth must be 1 through 8"));
    }
    let mut planes = Vec::new();
    for plane in 0..usize::from(depth) {
        planes.push(h.pointer(0, if color { 122 + plane * 4 } else { 92 }, bitmap_size)?);
    }
    let strip = planes[0];
    let locations = h.pointer(0, 98, count * 4)?;
    let space = if flags & 32 != 0 && u32_at(data, 102, BE)? != 0 {
        Some(h.pointer(0, 102, count * 2)?)
    } else {
        None
    };
    let kern = if u32_at(data, 106, BE)? != 0 {
        Some(h.pointer(0, 106, count * 2)?)
    } else {
        None
    };
    let ascent = i64::from(u16_at(data, 84, BE)?) + 1;
    let y = ascent - i64::from(height);
    let mut f = Font::default();
    f.metrics.pixel_size = Some(height);
    f.metrics.ascent = Some(ascent);
    f.metrics.descent = Some(-y);
    f.metrics.line_height = Some(i64::from(height));
    f.metrics.spacing = Some(if flags & 32 != 0 {
        Spacing::Proportional
    } else {
        Spacing::Monospaced
    });
    f.names.full = Some(latin(
        data[26..58].split(|x| *x == 0).next().unwrap_or_default(),
    ));
    f.names.version = Some(u16_at(data, 20, BE)?.to_string());
    f.charset = FontCharset {
        name: Some("iso8859-1".into()),
        ..Default::default()
    };
    for (name, value) in [
        ("amiga.style", i64::from(style)),
        ("amiga.flags", i64::from(flags)),
        ("amiga.x_size", i64::from(u16_at(data, 82, BE)?)),
        ("amiga.bold_smear", i64::from(u16_at(data, 86, BE)?)),
    ] {
        f.properties.push(Property::new(name, value));
    }
    budget.add(4096)?;
    if color {
        for (name, value) in [
            ("amiga.color_flags", i64::from(u16_at(data, 110, BE)?)),
            ("amiga.color_depth", i64::from(depth)),
            ("amiga.foreground", i64::from(data[113])),
            ("amiga.color_low", i64::from(data[114])),
            ("amiga.color_high", i64::from(data[115])),
            ("amiga.plane_pick", i64::from(data[116])),
            ("amiga.plane_on_off", i64::from(data[117])),
        ] {
            f.properties.push(Property::new(name, value));
        }
        if u32_at(data, 118, BE)? != 0 {
            let palette_header = h.pointer(0, 118, 8)?;
            let palette_count = usize::from(u16_at(palette_header, 2, BE)?);
            check(palette_count, 256, "Amiga palette entries")?;
            let target = *h.relocs.get(&(0, 118)).unwrap_or(&0);
            let header_offset = u32_at(data, 118, BE)? as usize;
            let palette = h.pointer(target, header_offset + 4, palette_count * 2)?;
            budget.add(palette.len() * 2 + 128)?;
            f.properties.push(Property::new(
                "amiga.palette",
                PropertyValue::Bytes(palette.to_vec()),
            ));
        }
    }
    for i in 0..count {
        let x = u16_at(locations, i * 4, BE)? as usize;
        let width = u32::from(u16_at(locations, i * 4 + 2, BE)?);
        let mut g = if color {
            check(
                width as usize * height as usize,
                l.max_pixels_per_glyph,
                "Amiga color glyph pixels",
            )?;
            if x.checked_add(width as usize)
                .is_none_or(|end| end > stride * 8)
            {
                return Err(invalid("Amiga color glyph exceeds strip"));
            }
            let n = width as usize * height as usize;
            budget.add(n.saturating_mul(2))?;
            let mut pixels = vec![0; n];
            for (plane, bytes) in planes.iter().enumerate() {
                for y in 0..height as usize {
                    for gx in 0..width as usize {
                        let bit = x + gx;
                        pixels[y * width as usize + gx] |=
                            ((bytes[y * stride + bit / 8] >> (7 - bit % 8)) & 1) << plane;
                    }
                }
            }
            let coverage = color_coverage(
                depth,
                u16_at(data, 110, BE)?,
                f.properties.get("amiga.palette"),
            )?;
            budget.add(pixels.len())?;
            let indices = pixels.clone();
            for p in &mut pixels {
                *p = coverage[*p as usize];
            }
            let mut g = Glyph::new(crate::bitmap::Bitmap::<crate::bitmap::Gray8>::from_raw(
                width,
                height,
                &pixels,
                bitmap_limits(l),
            )?);
            g.properties.push(Property::new(
                "amiga.color_indices",
                PropertyValue::Bytes(indices),
            ));
            g
        } else {
            Glyph::new(extract(strip, stride, x, width, height, l, budget)?)
        };
        let left = if let Some(k) = kern {
            i64::from(u16_at(k, i * 2, BE)? as i16)
        } else {
            0
        };
        let advance = if let Some(s) = space {
            i64::from(u16_at(s, i * 2, BE)? as i16)
        } else {
            i64::from(u16_at(data, 82, BE)?)
        };
        g.metrics.bounds = Bounds::new(width, height, left, y);
        g.metrics.advance = Some(Vector::new(advance, 0));
        if i + 1 < count {
            g.codepoints
                .push(Codepoint::Legacy(u32::from(first) + i as u32));
        }
        budget.add(128)?;
        let id = f.add_glyph(g)?;
        if i + 1 == count {
            f.metrics.default_glyph = Some(id);
        }
    }
    if color && u16_at(data,110,BE)? & 1 != 0 && f.properties.get("amiga.palette").is_some_and(|p|matches!(p,PropertyValue::Bytes(v) if v.as_chunks::<2>().0.iter().any(|c| {let rgb=u16::from_be_bytes(*c);(rgb>>8)&15!=(rgb>>4)&15 || (rgb>>4)&15!=rgb&15}))) {
        budget.diagnostic(report,"amiga","read.color_to_grayscale",crate::report::Impact::Loss,Some(fi),None,"RGB12 colors are projected to BT.601 grayscale coverage; original palette and indices are retained for exact source rewrite")?;
    }
    if h.segments.len() > 1 {
        budget.diagnostic(
            report,
            "amiga",
            "read.data_hunks",
            crate::report::Impact::None,
            Some(fi),
            None,
            "Resolved relocated font tables across multiple hunks without executing code",
        )?;
    }
    f.source_format = Some("amiga".into());
    Ok(f)
}
/// Encode one or more Amiga strikes, returning all descriptor and bitmap assets.
fn encode(
    source: &FontSet,
    w: &WriteOptions,
    o: &AmigaWriteOptions,
    report: &mut Report,
) -> Result<OutputBundle> {
    if o.color_depth.is_some_and(|depth| !(1..=8).contains(&depth)) {
        return Err(invalid("Amiga color depth must be 1 through 8"));
    }
    let mut budget = source_budget(source, &o.limits)?;
    let keep_color = o.color_depth.is_some()
        || source.fonts.iter().all(|f| {
            f.properties.get("amiga.color_depth").is_some()
                || f.glyphs()
                    .all(|(_, g)| matches!(g.bitmap, crate::model::GlyphBitmap::Mono(_)))
        });
    let converted = if keep_color {
        std::borrow::Cow::Borrowed(source)
    } else {
        convert_gray(source, o.gray_threshold, &o.limits, &mut budget)?
    };
    let s = converted.as_ref();
    if s.fonts.is_empty() {
        return Err(invalid("Amiga font set is empty"));
    }
    let contents = match o.packaging {
        Packaging::Contents => true,
        Packaging::Strike => false,
        Packaging::Auto => s.fonts.len() > 1 || w.primary_name.as_str().ends_with(".font"),
    };
    if !contents && s.fonts.len() != 1 {
        return Err(invalid("direct Amiga strike requires one font"));
    }
    check(s.fonts.len(), o.limits.max_resources, "Amiga strike count")?;
    let mut assets = Vec::new();
    let mut decoded = FontSet::default();
    let mut output_size = 0usize;
    let count = u16::try_from(s.fonts.len()).map_err(|_| invalid("too many Amiga strikes"))?;
    let mut descriptor = if contents {
        budget.add(4 + usize::from(count) * 260)?;
        vec![0; 4 + usize::from(count) * 260]
    } else {
        Vec::new()
    };
    let mut tagged = false;
    let mut total_glyphs = 0usize;
    let primary = w.primary_name.as_str();
    let basename = primary.rsplit('/').next().unwrap_or(primary);
    let dirname = basename.strip_suffix(".font").unwrap_or(basename);
    let prefix = primary.rsplit_once('/').map_or("", |(p, _)| p);
    let mut sizes = BTreeMap::new();
    for (fi, font) in s.fonts.iter().enumerate() {
        let mut local = Report::default();
        let mut result = encode_strike(font, o, &mut budget, &mut local);
        if let Err(crate::Error::ReportedErrors(errors)) = &mut result {
            for e in &mut errors.entries {
                e.location.font_index = Some(fi);
            }
        }
        for e in &mut local.entries {
            e.location.font_index = Some(fi);
        }
        report.extend(local);
        let bytes = result?;
        output_size = output_size
            .checked_add(bytes.len())
            .ok_or_else(|| invalid("Amiga output overflow"))?;
        check(output_size, o.max_output_bytes, "Amiga total output")?;
        let mut validation_report = Report::default();
        let mut read_font =
            parse_strike(&bytes, &o.limits, &mut budget, &mut validation_report, fi)?;
        total_glyphs += read_font.len();
        check(total_glyphs, o.limits.max_glyphs, "Amiga total glyphs")?;
        let path = if contents {
            let size = read_font.metrics.pixel_size.unwrap_or(0);
            let index = sizes.entry(size).or_insert(0usize);
            let leaf = if *index == 0 {
                size.to_string()
            } else {
                format!("{size}.{index}")
            };
            *index += 1;
            let rel = format!("{dirname}/{leaf}");
            let full = if prefix.is_empty() {
                rel.clone()
            } else {
                format!("{prefix}/{rel}")
            };
            let at = 4 + fi * 260;
            let mut tags = match font.headers.get("amiga.contents_tags") {
                Some(PropertyValue::Bytes(b)) if b.len() % 8 == 0 => b.clone(),
                None => Vec::new(),
                _ => {
                    return Err(invalid(
                        "amiga.contents_tags must contain 8-byte tag records",
                    ));
                }
            };
            budget.add(tags.len())?;
            if let Some(dpi) = font.metrics.resolution {
                let x = u16::try_from(dpi.x)
                    .map_err(|_| invalid("Amiga horizontal DPI out of range"))?;
                let y =
                    u16::try_from(dpi.y).map_err(|_| invalid("Amiga vertical DPI out of range"))?;
                if let Some(tag) = tags
                    .as_chunks_mut::<8>()
                    .0
                    .iter_mut()
                    .find(|t| matches!(u32_at(&t[..], 0, BE), Ok(0x80000001)))
                {
                    put16(tag, 4, x, BE);
                    put16(tag, 6, y, BE);
                } else {
                    tags.extend_from_slice(&[
                        0x80,
                        0,
                        0,
                        1,
                        (x >> 8) as u8,
                        x as u8,
                        (y >> 8) as u8,
                        y as u8,
                    ]);
                }
            }
            let tag_count = if tags.is_empty() {
                0
            } else {
                tags.len() / 8 + 1
            };
            check(tag_count, 31, "Amiga tags")?;
            let limit = if tag_count == 0 {
                254
            } else {
                256 - tag_count * 8
            };
            let name = latin_bytes(&rel)?;
            if name.len() >= limit {
                return Err(invalid("Amiga sidecar name exceeds contents capacity"));
            }
            descriptor[at..at + name.len()].copy_from_slice(&name);
            if tag_count > 0 {
                tagged = true;
                let pos = at + 256 - tag_count * 8;
                descriptor[pos..pos + tags.len()].copy_from_slice(&tags);
                put16(&mut descriptor, at + 254, tag_count as u16, BE);
                read_font.headers.push(Property::new(
                    "amiga.contents_tags",
                    PropertyValue::Bytes(tags),
                ));
                read_font.metrics.resolution = font.metrics.resolution;
            }
            put16(&mut descriptor, at + 256, size as u16, BE);
            descriptor[at + 258] = int(&read_font.properties, "amiga.style", 0)? as u8;
            descriptor[at + 259] = int(&read_font.properties, "amiga.flags", 0)? as u8;
            ResourcePath::new(full)?
        } else {
            w.primary_name.clone()
        };
        decoded.fonts.push(read_font);
        assets.push(OutputAsset { path, bytes });
    }
    if contents {
        put16(&mut descriptor, 0, if tagged { 0xf02 } else { 0xf00 }, BE);
        put16(&mut descriptor, 2, count, BE);
        output_size = output_size
            .checked_add(descriptor.len())
            .ok_or_else(|| invalid("Amiga output overflow"))?;
        check(
            descriptor.len(),
            o.limits.max_input_bytes.min(o.limits.max_table_bytes),
            "Amiga descriptor bytes",
        )?;
        check(output_size, o.max_output_bytes, "Amiga total output")?;
        assets.push(OutputAsset {
            path: w.primary_name.clone(),
            bytes: descriptor,
        });
    }
    audit(source, &decoded, "amiga", report, &mut budget)?;
    OutputBundle::new(w.primary_name.clone(), assets)
}
fn encode_strike(
    f: &Font,
    o: &AmigaWriteOptions,
    budget: &mut Budget,
    report: &mut Report,
) -> Result<Vec<u8>> {
    let slots = select(f, 255, o.unicode_as_latin1, "amiga", report, budget)?;
    let first = *slots
        .first_key_value()
        .ok_or_else(|| invalid("no Amiga mappings"))?
        .0;
    let last = *slots
        .last_key_value()
        .ok_or_else(|| invalid("no Amiga mappings"))?
        .0;
    let count = (last - first + 2) as usize;
    check(count, o.limits.max_glyphs, "Amiga glyphs")?;
    let fallback = f
        .metrics
        .default_glyph
        .and_then(|id| f.glyph(id))
        .or_else(|| {
            f.metrics
                .default_character
                .and_then(|cp| f.glyph_for_codepoint(cp))
        });
    let blank = Glyph::default();
    let default = fallback.unwrap_or(&blank);
    let all = slots.values().copied().chain(std::iter::once(default));
    let bottom = all
        .clone()
        .map(|g| -g.metrics.bounds.y)
        .max()
        .unwrap_or(0)
        .max(0);
    let ascent = all
        .clone()
        .map(|g| g.metrics.bounds.y + i64::from(g.bitmap.height()))
        .max()
        .unwrap_or(0)
        .max(1);
    let height =
        u16::try_from(ascent + bottom).map_err(|_| invalid("Amiga height out of range"))?;
    let mut width = 0usize;
    for cp in first..=last + 1 {
        let g = if cp > last {
            default
        } else {
            slots.get(&cp).copied().unwrap_or(default)
        };
        width = width
            .checked_add(g.bitmap.width() as usize)
            .ok_or_else(|| invalid("Amiga strip width overflow"))?;
    }
    check(width, 65535, "Amiga strip offset")?;
    let stride = width.div_ceil(16) * 2;
    let bitmap_size = stride * height as usize;
    let depth = o.color_depth.unwrap_or(
        u8::try_from(int(&f.properties, "amiga.color_depth", 0)?)
            .map_err(|_| invalid("Amiga color depth out of range"))?,
    );
    if depth > 8 {
        return Err(invalid("Amiga color depth must be at most 8"));
    }
    let color = depth > 0;
    let planes = usize::from(depth.max(1));
    let palette = if color {
        match f.properties.get("amiga.palette") {
            Some(PropertyValue::Bytes(v)) if v.len().is_multiple_of(2) && v.len() <= 512 => {
                v.clone()
            }
            None => {
                let levels = 1usize << depth;
                let mut p = vec![0; levels * 2];
                for i in 0..levels {
                    let gray = (i * 15 / (levels - 1)) as u16;
                    put16(&mut p, i * 2, gray * 0x111, BE);
                }
                p
            }
            _ => return Err(invalid("Amiga palette must be at most 256 RGB12 words")),
        }
    } else {
        Vec::new()
    };
    budget.add(palette.len())?;
    let anchor = if color { 162 + palette.len() } else { 110 };
    let loc = anchor + bitmap_size * planes;
    let space = loc + count * 4;
    let kern = space + count * 2;
    let len = (kern + count * 2).div_ceil(4) * 4;
    let reloc_count = 6 + if color { 2 + planes } else { 0 };
    let total = 32 + len + 4 + 4 + 4 + reloc_count * 4 + 4 + 4;
    check(
        total,
        o.max_output_bytes
            .min(o.limits.max_resource_bytes)
            .min(o.limits.max_input_bytes),
        "Amiga strike bytes",
    )?;
    check(len, o.limits.max_table_bytes, "Amiga hunk bytes")?;
    budget.add(total)?;
    let mut out = vec![0; total];
    for (at, v) in [
        (0, 0x3f3),
        (8, 1),
        (20, (len / 4) as u32),
        (24, 0x3e9),
        (28, (len / 4) as u32),
    ] {
        put32(&mut out, at, v, BE);
    }
    let data = &mut out[32..32 + len];
    put32(data, 0, 0x70ff4e75, BE);
    data[12] = 12;
    put32(data, 14, 26, BE);
    put16(data, 18, 0xf80, BE);
    let version = f
        .names
        .version
        .as_deref()
        .unwrap_or("0")
        .parse::<u16>()
        .unwrap_or(0);
    put16(data, 20, version, BE);
    let name: Vec<u8> = (f
        .names
        .full
        .as_deref()
        .or(f.names.family.as_deref())
        .unwrap_or(""))
    .chars()
    .take(32)
    .map(|c| u8::try_from(u32::from(c)).unwrap_or(b'?'))
    .collect();
    let take = name.len().min(32);
    data[26..26 + take].copy_from_slice(&name[..take]);
    data[66] = 12;
    put32(data, 68, 26, BE);
    put16(data, 78, height, BE);
    let style = u8::try_from(int(&f.properties, "amiga.style", 0)?)
        .map_err(|_| invalid("Amiga style out of range"))?
        & !64;
    data[80] = style | if color { 64 } else { 0 };
    data[81] = u8::try_from(int(&f.properties, "amiga.flags", 0x62)?)
        .map_err(|_| invalid("Amiga flags out of range"))?;
    if f.metrics.spacing != Some(Spacing::Monospaced) {
        data[81] |= 32;
    }
    put16(
        data,
        82,
        u16::try_from(int(
            &f.properties,
            "amiga.x_size",
            default.metrics.advance.map_or(0, |v| v.x),
        )?)
        .map_err(|_| invalid("Amiga X size out of range"))?,
        BE,
    );
    put16(data, 84, (ascent - 1) as u16, BE);
    put16(
        data,
        86,
        u16::try_from(int(&f.properties, "amiga.bold_smear", 1)?)
            .map_err(|_| invalid("Amiga smear out of range"))?,
        BE,
    );
    data[90] = first as u8;
    data[91] = last as u8;
    put32(data, 92, anchor as u32, BE);
    if color {
        put16(
            data,
            110,
            u16::try_from(int(&f.properties, "amiga.color_flags", 2)?)
                .map_err(|_| invalid("Amiga color flags out of range"))?,
            BE,
        );
        data[112] = depth;
        for (name, at, default) in [
            ("amiga.foreground", 113, 255),
            ("amiga.color_low", 114, 0),
            ("amiga.color_high", 115, (1i64 << depth) - 1),
            ("amiga.plane_pick", 116, 255),
            ("amiga.plane_on_off", 117, 0),
        ] {
            data[at] = u8::try_from(int(&f.properties, name, default)?)
                .map_err(|_| invalid("Amiga color field out of range"))?;
        }
        put32(data, 118, 154, BE);
        for plane in 0..planes {
            put32(
                data,
                122 + plane * 4,
                (anchor + plane * bitmap_size) as u32,
                BE,
            );
        }
        put16(data, 156, (palette.len() / 2) as u16, BE);
        put32(data, 158, 162, BE);
        data[162..anchor].copy_from_slice(&palette);
    }
    put16(data, 96, stride as u16, BE);
    put32(data, 98, loc as u32, BE);
    put32(data, 102, space as u32, BE);
    put32(data, 106, kern as u32, BE);
    let coverage = if color {
        color_coverage(
            depth,
            u16_at(data, 110, BE)?,
            Some(&PropertyValue::Bytes(palette.clone())),
        )?
    } else {
        [0; 256]
    };
    let mut nearest = [0u8; 256];
    if color {
        for (value, index) in nearest.iter_mut().enumerate() {
            *index = (0..(1usize << depth))
                .min_by_key(|i| u16::from(coverage[*i]).abs_diff(value as u16))
                .unwrap_or(0) as u8;
        }
    }
    let mut x = 0usize;
    for i in 0..count {
        let cp = first + i as u32;
        let g = if cp > last {
            default
        } else {
            slots.get(&cp).copied().unwrap_or(default)
        };
        let b = &g.bitmap;
        put16(data, loc + i * 4, x as u16, BE);
        put16(data, loc + i * 4 + 2, b.width() as u16, BE);
        let advance = g
            .metrics
            .advance
            .or(f.metrics.glyph_defaults.advance)
            .map_or(i64::from(b.width()), |v| v.x);
        put16(
            data,
            space + i * 2,
            i16::try_from(advance).map_err(|_| invalid("Amiga advance out of range"))? as u16,
            BE,
        );
        put16(
            data,
            kern + i * 2,
            i16::try_from(g.metrics.bounds.x).map_err(|_| invalid("Amiga bearing out of range"))?
                as u16,
            BE,
        );
        let top = usize::try_from(ascent - g.metrics.bounds.y - i64::from(b.height()))
            .map_err(|_| invalid("Amiga glyph outside cell"))?;
        if color {
            for gy in 0..b.height() as usize {
                for gx in 0..b.width() as usize {
                    let value = match b {
                        crate::model::GlyphBitmap::Mono(b) => {
                            if (b.as_bytes()[gy * b.stride() + gx / 8] >> (7 - gx % 8)) & 1 != 0 {
                                255
                            } else {
                                0
                            }
                        }
                        crate::model::GlyphBitmap::Gray8(b) => {
                            b.as_bytes()[gy * b.width() as usize + gx]
                        }
                    };
                    let cached = match g.properties.get("amiga.color_indices") {
                        Some(PropertyValue::Bytes(indices))
                            if indices.len() == b.width() as usize * b.height() as usize =>
                        {
                            indices.get(gy * b.width() as usize + gx).copied()
                        }
                        _ => None,
                    };
                    let value = cached
                        .filter(|index| {
                            u16::from(*index) < (1u16 << depth)
                                && coverage[*index as usize] == value
                        })
                        .unwrap_or(nearest[value as usize]);
                    for plane in 0..planes {
                        if value & (1 << plane) != 0 {
                            let bit = x + gx;
                            data[anchor + plane * bitmap_size + (top + gy) * stride + bit / 8] |=
                                0x80 >> (bit % 8);
                        }
                    }
                }
            }
        } else {
            insert(&mut data[anchor..loc], stride, x, top, mono(g)?);
        }
        x += b.width() as usize;
    }
    let tail = 32 + len;
    put32(&mut out, tail, 0x3ec, BE);
    put32(&mut out, tail + 4, reloc_count as u32, BE);
    let mut relocations = vec![14, 68, 92, 98, 102, 106];
    if color {
        relocations.extend([118, 158]);
        relocations.extend((0..planes).map(|p| 122 + p as u32 * 4));
    }
    for (i, off) in relocations.into_iter().enumerate() {
        put32(&mut out, tail + 12 + i * 4, off, BE);
    }
    put32(&mut out, tail + 16 + reloc_count * 4, 0x3f2, BE);
    Ok(out)
}

/// Encode and enforce strict mode before returning any output assets.
pub fn write(s: &FontSet, w: &WriteOptions, o: &AmigaWriteOptions) -> Result<Written> {
    let mut report = Report::default();
    let result = encode(s, w, o, &mut report);
    finish(result, report, "amiga", w.strict)
}

fn color_coverage(depth: u8, flags: u16, palette: Option<&PropertyValue>) -> Result<[u8; 256]> {
    let mut out = [0; 256];
    let levels = 1usize << depth;
    if flags & 1 != 0 {
        let Some(PropertyValue::Bytes(palette)) = palette else {
            return Err(invalid("Amiga color font is missing its palette"));
        };
        if palette.len() < levels * 2 {
            return Err(invalid("Amiga palette is shorter than color depth"));
        }
        for (i, p) in out.iter_mut().take(levels).enumerate() {
            let rgb = u16_at(palette, i * 2, BE)?;
            let r = u32::from((rgb >> 8) & 15) * 17;
            let g = u32::from((rgb >> 4) & 15) * 17;
            let b = u32::from(rgb & 15) * 17;
            *p = ((299 * r + 587 * g + 114 * b + 500) / 1000) as u8;
        }
    } else {
        for (i, p) in out.iter_mut().take(levels).enumerate() {
            *p = (i * 255 / (levels - 1)) as u8;
        }
    }
    Ok(out)
}

