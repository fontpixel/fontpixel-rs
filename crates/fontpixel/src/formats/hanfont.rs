/// Explicit native component arrangement; no filename/length guessing.
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq)]
pub enum Layout {
    /// 8×20 initials, 4×22 vowels, 4×28 finals; sixteen-square packed rasters.
    #[default]
    Johab844,
}
/// Model projection of a native component font.
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq)]
pub enum ReadMode {
    /// All 11,172 modern syllables, retaining the native component byte record.
    #[default]
    Syllables,
    /// All 360 native component slots as explicitly legacy codes.
    Components,
}
/// Explicit layout and requested projection.
#[derive(Debug, Clone, Default)]
pub struct HanfontReadOptions {
    /// Native layout.
    pub layout: Layout,
    /// Native component slots or composed syllables.
    pub mode: ReadMode,
}
/// Native component output; no inferred inverse decomposition is performed.
#[derive(Debug, Clone)]
pub struct HanfontWriteOptions {
    /// Native layout.
    pub layout: Layout,
    /// Explicit grayscale reduction for component glyphs.
    pub gray_threshold: Option<u8>,
    /// Cumulative source, output and default-readback budgets.
    pub limits: ResourceLimits,
    /// Maximum generated bytes.
    pub max_output_bytes: usize,
}
impl Default for HanfontWriteOptions {
    fn default() -> Self {
        Self {
            layout: Layout::Johab844,
            gray_threshold: None,
            limits: ResourceLimits::default(),
            max_output_bytes: 64 * 1024 * 1024,
        }
    }
}
/// Strongly typed registry codec.
#[derive(Debug, Clone, Default)]
pub struct HanfontCodec {
    /// Input interpretation.
    pub read_options: HanfontReadOptions,
    /// Output policy.
    pub write_options: HanfontWriteOptions,
}
impl FormatDetector for HanfontCodec {
    fn detect(&self, _: &mut ReadContext<'_>) -> Result<Confidence> {
        Ok(Confidence::NoMatch)
    }
}
impl FormatReader<FontSet> for HanfontCodec {
    fn read(&self, c: &mut ReadContext<'_>, _: &ReadOptions) -> Result<(FontSet, Report)> {
        read(c.bytes(), &self.read_options, c.limits())
    }
}
impl FormatWriter<FontSet> for HanfontCodec {
    fn write(&self, s: &FontSet, o: &WriteOptions) -> Result<Written> {
        let (bytes, report) = write(s, &self.write_options)?;
        Ok(Written {
            output: OutputBundle::single(o.primary_name.clone(), bytes),
            report,
        })
    }
}
/// Headerless data cannot be positively identified by content.
pub fn detect(_: &[u8]) -> Confidence {
    Confidence::NoMatch
}
/// Read exactly 360 native components, optionally composing all modern syllables.
pub fn read(
    data: &[u8],
    o: &HanfontReadOptions,
    limits: &ResourceLimits,
) -> Result<(FontSet, Report)> {
    let mut b = Budget::new(limits);
    check(data.len(), limits.max_input_bytes, "hanfont input bytes")?;
    b.add(data.len())?;
    Ok((decode(data, o.mode, &mut b)?, Report::default()))
}
const COMPONENTS: usize = 360;
const BYTES: usize = COMPONENTS * 32;
const SYLLABLES: usize = 19 * 21 * 28;
fn decode(data: &[u8], mode: ReadMode, b: &mut Budget<'_>) -> Result<FontSet> {
    if data.len() != BYTES {
        return Err(invalid("hanfont Johab844 requires exactly 360 × 32 bytes"));
    }
    b.table(data.len())?;
    b.add(4096)?;
    let count = if mode == ReadMode::Components {
        COMPONENTS
    } else {
        SYLLABLES
    };
    check(count, b.limits.max_glyphs, "hanfont glyph count")?;
    let mut f = Font::default();
    f.source_format = Some("hanfont".into());
    f.charset = FontCharset {
        name: Some(
            if mode == ReadMode::Components {
                "johab844-components"
            } else {
                "unicode"
            }
            .into(),
        ),
        ..Default::default()
    };
    f.metrics = FontMetrics {
        pixel_size: Some(16),
        ascent: Some(16),
        descent: Some(0),
        bounds: Some(Bounds::new(16, 16, 0, 0)),
        spacing: Some(Spacing::CharacterCell),
        ..Default::default()
    };
    f.properties.push(Property::new(
        "hanfont.layout",
        PropertyValue::Text("johab844".into()),
    ));
    f.properties.push(Property::new(
        "hanfont.components",
        PropertyValue::Bytes(data.to_vec()),
    ));
    for index in 0..count {
        b.glyph(16, 16)?;
        let raster = if mode == ReadMode::Components {
            data[index * 32..index * 32 + 32]
                .try_into()
                .expect("fixed component")
        } else {
            compose(data, index)
        };
        let mut g = Glyph::new(Bitmap::<crate::bitmap::Mono>::from_raw(
            16,
            16,
            &raster,
            bitmap_limits(b.limits),
        )?);
        g.codepoints.push(if mode == ReadMode::Components {
            Codepoint::Legacy(index as u32)
        } else {
            Codepoint::Unicode(0xac00 + index as u32)
        });
        g.metrics.advance = Some(Vector::new(16, 0));
        f.add_glyph(g)?;
    }
    let mut s = FontSet::from(f);
    s.source_format = Some("hanfont".into());
    Ok(s)
}
/// Return the three component slots for a modern Hangul syllable. An absent
/// final is represented by `None`; filler artwork is never mistaken for a final.
pub fn component_slots(codepoint: u32) -> Result<(usize, usize, Option<usize>)> {
    if !(0xac00..=0xd7a3).contains(&codepoint) {
        return Err(invalid("not a modern Hangul syllable"));
    }
    let n = (codepoint - 0xac00) as usize;
    let initial = n / (21 * 28);
    let vowel = n / 28 % 21;
    let final_ = n % 28;
    // Factual grouping transcribed from the published 8/4/4 tables.
    let shape = match vowel {
        0..=7 | 20 => 0,
        8 | 12 | 18 => 1,
        13 | 17 => 2,
        9..=11 | 19 => 3,
        _ => 4,
    };
    let initial_form = if final_ == 0 {
        shape
    } else {
        match shape {
            0 => 5,
            1 | 2 => 6,
            _ => 7,
        }
    };
    let vowel_form = usize::from(initial != 0 && initial != 15) + 2 * usize::from(final_ != 0);
    let final_form = match vowel {
        0 | 2 | 9 => 0,
        4 | 6 | 11 | 14 | 16 | 19 | 20 => 1,
        1 | 3 | 5 | 7 | 10 | 15 => 2,
        _ => 3,
    };
    Ok((
        initial_form * 20 + initial + 1,
        160 + vowel_form * 22 + vowel + 1,
        (final_ != 0).then_some(248 + final_form * 28 + final_),
    ))
}
fn compose(data: &[u8], n: usize) -> [u8; 32] {
    let (i, v, t) = component_slots(0xac00 + n as u32).expect("bounded syllable index");
    let mut out = [0; 32];
    for k in 0..32 {
        out[k] = data[i * 32 + k] | data[v * 32 + k] | t.map_or(0, |t| data[t * 32 + k]);
    }
    out
}
/// Write complete native components, or verify retained components reproduce a
/// complete syllable font. Nonrepresentable syllables return an explicit error.
pub fn write(s: &FontSet, o: &HanfontWriteOptions) -> Result<(Vec<u8>, Report)> {
    let mut b = Budget::new(&o.limits);
    b.model(s)?;
    let f = s.single()?;
    check(
        BYTES,
        o.max_output_bytes.min(o.limits.max_input_bytes),
        "hanfont output bytes",
    )?;
    b.table(BYTES)?;
    let mut report = Report::default();
    let components = f.len() == COMPONENTS
        && f.glyphs().all(|(_, g)| {
            g.codepoints.len() == 1
                && matches!(g.codepoints[0], Codepoint::Legacy(v) if v < COMPONENTS as u32)
        });
    let data = if components {
        let mut out = vec![0; BYTES];
        let mut seen = [false; COMPONENTS];
        let mut gray = false;
        for (_, g) in f.glyphs() {
            let at = g.codepoints[0].value() as usize;
            if std::mem::replace(&mut seen[at], true) {
                return Err(invalid("hanfont duplicate component slot"));
            }
            if g.metrics.bounds != Bounds::new(16, 16, 0, 0) {
                return Err(invalid("hanfont components require 16×16 bounds at (0,0)"));
            }
            match &g.bitmap {
                GlyphBitmap::Mono(m) => out[at * 32..at * 32 + 32].copy_from_slice(m.as_bytes()),
                GlyphBitmap::Gray8(m) => {
                    let threshold = o
                        .gray_threshold
                        .ok_or_else(|| invalid("hanfont Gray8 requires explicit threshold"))?;
                    gray = true;
                    for (p, &value) in m.as_bytes().iter().enumerate() {
                        if value >= threshold {
                            out[at * 32 + p / 8] |= 0x80 >> (p % 8);
                        }
                    }
                }
            }
        }
        if gray {
            b.loss(
                &mut report,
                "hanfont.gray_threshold",
                "Gray8 components were reduced using the explicit threshold",
            )?;
        }
        out
    } else {
        let raw = bytes(&f.properties,"hanfont.components").filter(|raw| raw.len() == BYTES).ok_or_else(|| invalid("hanfont writing syllables requires retained native components; inverse decomposition is undefined"))?;
        if f.len() != SYLLABLES {
            return Err(invalid(
                "hanfont requires the complete syllable projection or all component slots",
            ));
        }
        for n in 0..SYLLABLES {
            let g = f
                .glyph_for_codepoint(Codepoint::Unicode(0xac00 + n as u32))
                .ok_or_else(|| invalid("hanfont syllable projection is incomplete"))?;
            if g.codepoints != [Codepoint::Unicode(0xac00 + n as u32)]
                || g.metrics.bounds != Bounds::new(16, 16, 0, 0)
                || !matches!(g.bitmap, GlyphBitmap::Mono(_))
                || g.bitmap.as_bytes() != compose(raw, n)
            {
                return Err(invalid(
                    "hanfont edited syllable cannot be reproduced by retained components",
                ));
            }
        }
        raw.to_vec()
    };
    // Default readback is always possible, even for an explicit components write.
    let decoded = decode(&data, ReadMode::Syllables, &mut b)?;
    if components {
        drop(decoded);
        let native = decode(&data, ReadMode::Components, &mut b)?;
        compare(s, &native, "hanfont", &mut b, &mut report)?;
    } else {
        compare(s, &decoded, "hanfont", &mut b, &mut report)?;
    }
    Ok((data, report))
}
