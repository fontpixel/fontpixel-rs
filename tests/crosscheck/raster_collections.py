#!/usr/bin/env python3
"""W2.7 complete-glyph raster, collection and independent-tool comparisons.

Prior accepted W2.6 fixtures are read-only inputs, not regenerated proof. Every
raster result is generated by this build. Reproducible fixture generation is in
variants.py/variants_latin.py. No protected reference or sample data is modified.
"""
import argparse,hashlib,json,logging,subprocess,time
from pathlib import Path
import freetype,ots,uharfbuzz as hb
from fontTools.ttLib import TTFont,TTCollection
logging.getLogger('fontTools.ttLib.tables._h_e_a_d').setLevel(logging.ERROR)

def call(*args):
 p=subprocess.run([str(x) for x in args],capture_output=True,text=True)
 if p.returncode:raise RuntimeError((args,p.stdout,p.stderr))
 return p.stdout

def pixels(g):
 w,h,x,y=g['bbox'];data=g['pixels'];stride=(w+7)//8
 return {(x+xx,y+h-yy-1)for yy in range(h)for xx in range(w)if(data[yy*stride+xx//8]>>(7-xx%8))&1}

def ft_ink(face,gid):
 face.load_glyph(gid,freetype.FT_LOAD_RENDER|freetype.FT_LOAD_TARGET_MONO|freetype.FT_LOAD_NO_HINTING|freetype.FT_LOAD_NO_BITMAP)
 s=face.glyph;b=s.bitmap;d=bytes(b.buffer)
 return {(s.bitmap_left+x,s.bitmap_top-y-1)for y in range(b.rows)for x in range(b.width)if(d[y*abs(b.pitch)+x//8]>>(7-x%8))&1},round(s.advance.x/64)

def shape(data,index=0):
 f=hb.Font(hb.Face(data,index));f.scale=(1400,1400);out=[]
 for lang in ['zh-Hans','zh-Hant','zh-HK','ja','ko','en']:
  b=hb.Buffer();b.add_str('A中骨国“…”');b.guess_segment_properties();b.language=lang;hb.shape(f,b)
  out.append([(g.codepoint,p.x_advance,p.y_advance,p.x_offset,p.y_offset)for g,p in zip(b.glyph_infos,b.glyph_positions)])
 return out

def raster_case(driver,path,work,ppem,prefer=False):
 out=work/'current-raster.json';call(driver,'read',path,out,ppem,'embedded'if prefer else'outline');parsed=json.loads(out.read_text());assert len(parsed['fonts'])==1
 f=TTFont(path);f.ensureDecompiled();order=f.getGlyphOrder();face=freetype.Face(str(path));face.set_pixel_sizes(0,ppem);records=parsed['fonts'][0]['glyphs'];assert len(records)==len(order)
 cmap={cp:f.getGlyphID(name)for cp,name in f.getBestCmap().items()};actual={cp:g['gid']for g in records for cp in g['cps']};assert cmap==actual
 count=0;exceptions=[]
 for g in records:
  gid=g['gid'];ink,advance=ft_ink(face,gid);assert g['advance'][0]==advance,(path.name,gid,'advance',g['advance'],advance)
  got=pixels(g)
  if got!=ink:
   # Tong's reusable dot component is centered on (0,0). No pixel centers
   # fall inside its 0.9px disk, while FreeType dropout control forces ink.
   assert 'dot' in path.name and 'glyf'in f and gid==len(order)-1 and not got,(path.name,gid,len(got),len(ink),sorted(got^ink)[:8])
   exceptions.append({'gid':gid,'reason':'origin-centered standalone helper: exact centers empty; FreeType dropout ink','freetype_pixels':sorted(ink)})
  else:count+=1
 return {'file':path.name,'sha256':hashlib.sha256(path.read_bytes()).hexdigest(),'glyphs':len(records),'exact_freetype_glyphs':count,'exceptions':exceptions,'native_seconds':parsed['seconds'],'ppem':ppem}

def collection_cases(driver,work,inputs,reference):
 paths=inputs[:2];native=work/'native.ttc';call(driver,'collect',native,*paths,paths[0]);fonts=TTCollection(native).fonts;assert len(fonts)==3
 shared=[]
 for t in fonts[0].reader.tables:
  if t in fonts[2].reader.tables:assert fonts[0].reader.tables[t].offset==fonts[2].reader.tables[t].offset;shared.append(t)
 for i,source in enumerate([*paths,paths[0]]):
  f=fonts[i];f.ensureDecompiled();s=TTFont(source);assert f.getGlyphOrder()==s.getGlyphOrder();assert f.getBestCmap()==s.getBestCmap();assert shape(native.read_bytes(),i)==shape(source.read_bytes())
  ft=freetype.Face(str(native),index=i);assert ft.num_glyphs==len(s.getGlyphOrder())
  extracted=work/f'face-{i}.ttf';call(driver,'extract',native,extracted,i);ots.sanitize(str(extracted),check=True);x=TTFont(extracted);x.ensureDecompiled()
  for t in s.keys():
   if t in ['GlyphOrder','head','DSIG']:continue
   assert s.reader[t]==x.reader[t],(i,t)
 # Independent fontTools writer -> native reader, including table sharing.
 external=work/'fonttools.ttc';c=TTCollection();c.fonts=[TTFont(p)for p in [*paths,paths[0]]];c.save(external,shareTables=True)
 for i in range(3):call(driver,'extract',external,work/f'external-{i}.ttf',i)
 # WOFF2 collection supports paired glyf/loca transforms, CFF and shared faces.
 web=work/'collection.woff2';restored=work/'restored.ttc';call(driver,'web',native,web);call(driver,'unweb',web,restored)
 restored_fonts=TTCollection(restored).fonts;assert len(restored_fonts)==3
 for i in range(3):assert shape(restored.read_bytes(),i)==shape(native.read_bytes(),i);restored_fonts[i].ensureDecompiled()
 # Independently reconstruct with Google's decoder; each extracted face passes OTS.
 google=work/'google.ttc'
 call(reference,'decode',web,google)
 gc=TTCollection(google)
 for i in range(3):
  gc.fonts[i].ensureDecompiled();assert shape(google.read_bytes(),i)==shape(native.read_bytes(),i)
  path=work/f'google-face-{i}.ttf';call(driver,'extract',google,path,i);ots.sanitize(str(path),check=True)
 # Installed OTS rejects this mixed TrueType/CFF face sequence. Prove
 # its same failure on an independently written fontTools TTC before classifying.
 tool_limits=[]
 for path in [native,external,google,web]:
  result=ots.sanitize(str(path),capture_output=True)
  assert result.returncode==1 and b'maxp: wrong maxp version for glyph data'in result.stderr,(path,result.stderr)
  tool_limits.append({'file':path.name,'tool':'OTS','returncode':result.returncode,'stderr':result.stderr.decode().strip()})
 # Google's independently compressed collection reproduces the deployed
 # FreeType WOFF2 non-first-CFF-face limitation. Raw reconstructed TTCs work.
 external_web=work/'google-compressed.woff2';call(reference,native,external_web,3)
 for path in [web,external_web]:
  for i in [0,2]:
   ft=freetype.Face(str(path),index=i);assert ft.num_faces==3
  try:freetype.Face(str(path),index=1)
  except freetype.FT_Exception as error:tool_limits.append({'file':path.name,'tool':'FreeType WOFF2 CFF face 1','error':str(error)})
  else:raise AssertionError('upstream FreeType limitation changed; refresh expected evidence')
 homogeneous=[]
 for kind in ['ttf','otf']:
  source=paths[0]if kind=='ttf'else paths[1];ttc=work/f'{kind}-homogeneous.ttc';w=work/f'{kind}-homogeneous.woff2';call(driver,'collect',ttc,source,source);call(driver,'web',ttc,w)
  ots.sanitize(str(ttc),check=True);ots.sanitize(str(w),check=True)
  homogeneous.append({'flavor':kind,'faces':2,'ots_ttc':True,'ots_woff2':True})
 return {'faces':3,'shared_tags':sorted(shared),'fonttools_writer_roundtrip':True,'woff2_bytes':web.stat().st_size,'google_decoder_all_faces':True,'ots_extracted_faces':6,'homogeneous':homogeneous,'tool_limitations':tool_limits,'harfbuzz_language_batches':54}

def main():
 p=argparse.ArgumentParser();p.add_argument('--driver',type=Path,required=True);p.add_argument('--reference',type=Path,required=True);p.add_argument('--full-work',type=Path,required=True);p.add_argument('--latin-work',type=Path,required=True);p.add_argument('--work',type=Path,required=True);p.add_argument('--output',type=Path,required=True);a=p.parse_args();a.work.mkdir(parents=True,exist_ok=True);results=[]
 paths=[a.full_work/f'full-{shape}-{kind}.{kind}'for shape in ['square','dot']for kind in ['ttf','otf']]
 paths+=sorted(p for p in a.latin_work.glob('*.ttf')if p.name.endswith('-ttf.ttf'))+sorted(p for p in a.latin_work.glob('*.otf')if p.name.endswith('-otf.otf'))
 for path in paths:
  ppem=TTFont(path)['head'].unitsPerEm//100
  result=raster_case(a.driver,path,a.work,ppem);results.append(result);print(path.name,'PASS',result['glyphs'],result['native_seconds'],flush=True);a.output.write_text(json.dumps({'partial':True,'raster':results},indent=2)+'\n')
 collections=collection_cases(a.driver,a.work,paths[:2],a.reference);a.output.write_text(json.dumps({'partial':False,'raster':results,'collections':collections},indent=2)+'\n');print('COLLECTIONS PASS',flush=True)
if __name__=='__main__':main()
