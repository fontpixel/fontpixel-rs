#!/usr/bin/env python3
"""Independent catalogue, Pillow, C compiler and monobit checks for image/C codecs."""
import argparse
import hashlib
import json
import subprocess
import sys
from pathlib import Path

import monobit
from PIL import Image

ROOT = Path(__file__).resolve().parents[2]
sys.dont_write_bytecode = True
sys.path.insert(0, str(ROOT.parent / "reference/fontpixel/pipeline"))
from opf.ingest.header8x8 import convert_font8x8
from opf.parsers.bdf import parse_bdf


def signature(g):
    return g.cp, g.bbw, g.bbh, g.bbx, g.bby, g.dwidth, g.rows


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--binary", type=Path, required=True)
    p.add_argument("--headers", type=Path, required=True)
    p.add_argument("--output-dir", type=Path, required=True)
    p.add_argument("--tong", action="store_true")
    args = p.parse_args()
    binary = str(args.binary.resolve())
    dest = args.output_dir.resolve()
    dest.mkdir(parents=True, exist_ok=False)
    results = {"checks": [], "artifacts": {}}

    def command(*argv):
        result = subprocess.run([binary, *map(str, argv)], capture_output=True)
        assert result.returncode == 0, (argv, result.stderr.decode())
        return result

    source = args.headers.resolve() / "font8x8.h"
    expected = convert_font8x8(source, "font8x8")
    decoded = dest / "font8x8.bdf"
    result = command("convert", source, "-o", decoded, "--report", "json")
    imported = parse_bdf(decoded, "font8x8")
    assert list(map(signature, imported.glyphs)) == list(map(signature, expected.glyphs))
    assert (imported.ascent, imported.descent) == (7, 1)
    report = json.loads(result.stdout)["report"]["entries"]
    assert sum(e["code"] == "c.read.unmapped_row" for e in report) == len(expected.warnings)
    results["checks"].append({"oracle": "catalogue font8x8", "glyphs": len(expected.glyphs), "omissions": len(expected.warnings)})
    ascii_glyphs = [g for g in expected.glyphs if 32 <= g.cp <= 127]
    assert len(ascii_glyphs) == 96

    generic = dest / "generic.h"
    gfx = dest / "gfx.h"
    for target, family in [(generic, "generic"), (gfx, "gfx")]:
        command("convert", decoded, "-o", target, "--to", "c", "--c-family", family, "--c-range", "U+0020-U+007F")
    # The compiler sees the exact generated bytes, including option comments.
    harness = dest / "generic-check.c"
    harness.write_text('#include <stdio.h>\n#include "generic.h"\nint main(void) { return fwrite(font,1,sizeof(font),stdout) == sizeof(font) ? 0 : 1; }\n')
    subprocess.run(["cc", "-std=c11", "-pedantic-errors", "-Wall", "-Wextra", "-Werror", str(harness), "-o", str(dest / "generic-check")], check=True)
    compiled = subprocess.check_output([str(dest / "generic-check")])
    assert compiled == b"".join(g.rows for g in ascii_glyphs)
    # Original test structure definitions matching the documented Adafruit ABI.
    (dest / "gfxfont.h").write_text('#include <stdint.h>\ntypedef struct { uint16_t bitmapOffset; uint8_t width,height,xAdvance; int8_t xOffset,yOffset; } GFXglyph;\ntypedef struct { uint8_t *bitmap; GFXglyph *glyph; uint16_t first,last; uint8_t yAdvance; } GFXfont;\n')
    harness = dest / "gfx-check.c"
    harness.write_text('#include "gfx.h"\nint main(void) { return font.first == 32 && font.last == 127 && font.glyph[33].width == 8 && font.bitmap[0] == 0 ? 0 : 1; }\n')
    subprocess.run(["cc", "-std=c11", "-pedantic-errors", "-Wall", "-Wextra", "-Werror", "-I", str(dest), str(harness), "-o", str(dest / "gfx-check")], check=True)
    subprocess.run([str(dest / "gfx-check")], check=True)
    loaded = monobit.load(gfx, format="gfxfont")[0]
    assert len(loaded.glyphs) == 96
    for g, old in zip(loaded.glyphs, ascii_glyphs):
        assert int.from_bytes(bytes(g.codepoint), "big") == old.cp
        assert g.as_bytes() == old.rows
        assert (g.width, g.height, g.advance_width, g.left_bearing, g.shift_up) == (old.bbw, old.bbh, old.dwidth, old.bbx, old.bby)
    results["checks"].append({"oracle": "C11 compiler + monobit GFX", "glyphs": 96})

    for ext in ["png", "bmp", "gif", "tga", "pbm", "pgm"]:
        image = dest / f"atlas-{ext}.{ext}"
        command("convert", decoded, "-o", image, "--to", "image", "--strict")
        mapping = json.loads(image.with_suffix(".json").read_text())
        pixels = Image.open(image).convert("RGB")
        for cell, g in zip(mapping["cells"], imported.glyphs):
            x, y, w, h = cell["rect"]
            assert (w, h) == (g.bbw, g.bbh)
            assert cell["native"]["codepoints"] == [{"Unicode": g.cp}]
            for py in range(h):
                for px in range(w):
                    value = 255 if g.rows[py * ((w + 7) // 8) + px // 8] & (128 >> (px % 8)) else 0
                    assert pixels.getpixel((x + px, y + py)) == (value, value, value), (ext, g.cp, px, py)
        restored = dest / f"atlas-{ext}.bdf"
        command("convert", image, "-o", restored, "--strict")
        assert restored.read_bytes() == decoded.read_bytes()
        results["checks"].append({"oracle": f"Pillow {ext} + canonical BDF", "glyphs": len(imported.glyphs)})
    if args.tong:
        source = ROOT.parent / "samples/tong-pixel-sans/TongPixelSans14Large-SC.bdf"
        canonical = dest / "tong-canonical.bdf"
        command("convert", source, "-o", canonical, "--strict")
        image = dest / "tong.png"
        command("convert", source, "-o", image, "--to", "image", "--strict")
        restored = dest / "tong-restored.bdf"
        command("convert", image, "-o", restored, "--strict")
        assert restored.read_bytes() == canonical.read_bytes()
        results["checks"].append({"oracle": "full Tong canonical BDF roundtrip", "glyphs": len(parse_bdf(source, "tong").glyphs)})
    for path in sorted(dest.iterdir()):
        if path.is_file():
            results["artifacts"][path.name] = {"bytes": path.stat().st_size, "sha256": hashlib.sha256(path.read_bytes()).hexdigest()}
    (dest / "results.json").write_text(json.dumps(results, indent=2) + "\n")
    print(json.dumps(results["checks"], indent=2))


if __name__ == "__main__":
    main()
